def plot_response_curves(samples: dict,
                          inputs: dict,
                          save_path: str = "outputs/fig_response_curves.png"):
    """
    Posterior Hill saturation curves with 90% credible bands.

    For each channel × region combination, we:
      1. Draw the posterior mean response curve (Hill function at posterior mean k, ec).
      2. Shade the 5th–95th percentile band across all posterior draws.
      3. Mark the current operating point — the mean normalised adstock at
         current spend levels — as a vertical line.
      4. Overlay the true DGP curve (dashed black) for validation.

    The current operating point relative to the curve shape directly answers:
        "Are we in the diminishing returns zone for this channel?"

    If the operating point is to the right of the inflection point (roughly
    where the curve bends from convex to concave), the channel is saturating
    and marginal returns are declining. This motivates the optimisation in
    Phase 6.
    """
    print("\n  Plotting response curves...")

    x_grid = np.linspace(0, 2.0, 300)   # normalised adstock axis

    # Channel → region parameter index mapping
    ch_param = {
        "tv":          ("alpha_tv",   "k_tv",   "ec_tv",   "beta_tv"),
        "paid_search": ("alpha_ps",   "k_ps",   "ec_ps",   "beta_ps"),
        "social":      ("alpha_so",   "k_so",   "ec_so",   "beta_so"),
        "display":     ("alpha_disp", "k_disp", "ec_disp", "beta_disp"),
    }

    fig, axes = plt.subplots(N_REGIONS, len(CHANNELS),
                              figsize=(5 * len(CHANNELS), 4 * N_REGIONS))
    fig.suptitle(
        "MapleThread — Posterior Response Curves (Hill Saturation)\n"
        "Shaded band = 90% credible interval  |  Dashed black = true DGP curve\n"
        "Vertical line = current mean operating point (normalised adstock)",
        fontsize=13, fontweight="bold", y=1.01,
    )

    for r, region in enumerate(REGIONS):
        for c, ch in enumerate(CHANNELS):
            ax = axes[r, c]
            color = PALETTE[ch]

            a_key, k_key, ec_key, b_key = ch_param[ch]

            # Posterior samples for this region's parameters
            alpha_draws = samples[a_key][:, r]   # (D,)
            k_draws     = samples[k_key][:, r]
            ec_draws    = samples[ec_key][:, r]

            # Evaluate Hill curve for every posterior draw across x_grid
            # Shape broadcast: (D, 1) op (1, 300) → (D, 300)
            k_2d  = k_draws[:, None]
            ec_2d = ec_draws[:, None]
            x_2d  = x_grid[None, :]

            curves = hill_saturation_np(x_2d, k_2d, ec_2d)   # (D, 300)

            curve_mean = curves.mean(axis=0)
            curve_lo   = np.percentile(curves,  5, axis=0)
            curve_hi   = np.percentile(curves, 95, axis=0)

            ax.fill_between(x_grid, curve_lo, curve_hi,
                            alpha=0.25, color=color)
            ax.plot(x_grid, curve_mean, color=color, lw=2.0,
                    label="Posterior mean")

            # True DGP curve
            k_true  = TRUE_PARAMS["hill_k"][ch]
            ec_true = TRUE_PARAMS["hill_ec"][ch]
            true_curve = hill_saturation_np(x_grid, k_true, ec_true)
            ax.plot(x_grid, true_curve, color="black", lw=1.5,
                    linestyle="--", alpha=0.7, label="True DGP")

            # Current operating point: mean adstock_norm at posterior mean alpha
            alpha_mean = float(alpha_draws.mean())
            p95_val    = inputs["p95"][ch][r]
            spend_r    = inputs["spend"][ch][r]
            adstock_norm = compute_current_adstock_norm(spend_r, alpha_mean, p95_val)
            current_x    = float(adstock_norm.mean())

            ax.axvline(current_x, color=color, lw=1.8, linestyle=":",
                       alpha=0.85, label=f"Current x̄={current_x:.2f}")

            # Half-saturation reference lines
            ax.axhline(0.5, color="grey", lw=0.8, linestyle="--", alpha=0.5)

            if r == 0:
                ax.set_title(CHANNEL_LABELS[ch], fontsize=11,
                             fontweight="bold", color=color)
            if c == 0:
                ax.set_ylabel(REGION_LABELS[region], fontsize=9,
                              fontweight="bold")

            ax.set_xlim(0, 2.0)
            ax.set_ylim(0, 1.05)
            ax.set_xlabel("Normalised adstock", fontsize=8)
            ax.legend(fontsize=6.5, loc="lower right")

    plt.tight_layout()
    plt.savefig(save_path, dpi=130, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Response curves saved: {save_path}")


