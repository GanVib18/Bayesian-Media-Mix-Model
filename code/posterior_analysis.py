def get_posterior_samples(idata: az.InferenceData) -> dict:
    """
    Extract and flatten posterior samples for all per-region parameters.

    Returns a dict mapping parameter name → np.ndarray of shape (n_draws, R)
    for vector parameters, or (n_draws,) for scalars.

    Flattening chains × draws into a single draw dimension simplifies all
    downstream computation — we treat the joint posterior as a single set
    of samples.
    """
    posterior = idata.posterior
    chains    = posterior.dims["chain"]
    draws     = posterior.dims["draw"]
    D         = chains * draws   # total posterior draws

    samples = {}

    # Per-region parameters: shape (chains, draws, R) → (D, R)
    per_region_params = [
        "alpha_tv", "alpha_ps", "alpha_so", "alpha_disp",
        "k_tv",     "k_ps",     "k_so",     "k_disp",
        "ec_tv",    "ec_ps",    "ec_so",    "ec_disp",
        "beta_tv",  "beta_ps",  "beta_so",  "beta_disp",
        "intercept", "trend_slope",
    ]
    for p in per_region_params:
        if p in posterior:
            arr = posterior[p].values   # (chains, draws, R)
            samples[p] = arr.reshape(D, N_REGIONS)

    # Contribution deterministics: shape (chains, draws, T) — one per region/channel
    for region in REGIONS:
        for ch in CHANNELS:
            key = f"contrib_{ch}_{region}"
            if key in posterior:
                arr = posterior[key].values   # (chains, draws, T)
                samples[key] = arr.reshape(D, N_WEEKS)

        key_bl = f"baseline_{region}"
        if key_bl in posterior:
            samples[key_bl] = posterior[key_bl].values.reshape(D, N_WEEKS)

    # mu: shape (chains, draws, R, T) → (D, R, T)
    if "mu" in posterior:
        samples["mu"] = posterior["mu"].values.reshape(D, N_REGIONS, N_WEEKS)

    print(f"  Extracted {D} posterior draws ({chains} chains × {draws} draws).")
    return samples


def hill_saturation_np(x: np.ndarray, k: float | np.ndarray,
                        ec: float | np.ndarray) -> np.ndarray:
    """Numpy Hill saturation — vectorised over arbitrary shapes."""
    safe_x = np.where(x == 0.0, 1e-10, x)
    return safe_x**k / (safe_x**k + ec**k)


def hill_derivative_np(x: np.ndarray, k: float | np.ndarray,
                        ec: float | np.ndarray) -> np.ndarray:
    """
    Analytical derivative of Hill function w.r.t. x.

        dS/dx = k * ec^k * x^(k-1) / (x^k + ec^k)^2

    Used to compute marginal ROAS at current spend levels.
    """
    safe_x      = np.where(x <= 0, 1e-10, x)
    numerator   = k * (ec**k) * (safe_x ** (k - 1))
    denominator = (safe_x**k + ec**k) ** 2
    return np.where(x <= 0, 0.0, numerator / denominator)


def compute_current_adstock_norm(spend_r: np.ndarray, alpha: float,
                                  p95_val: float) -> np.ndarray:
    """
    Compute geometric adstock for a single region/channel spend series,
    normalised by p95. Pure numpy — used for ROAS computation.
    """
    T       = len(spend_r)
    adstock = np.empty(T, dtype=float)
    adstock[0] = spend_r[0]
    for t in range(1, T):
        adstock[t] = spend_r[t] + alpha * adstock[t - 1]
    return adstock / p95_val if p95_val > 0 else adstock


