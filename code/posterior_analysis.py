# 6. MARGINAL ROAS
# ══════════════════════════════════════════════════════════════════════════════

def compute_marginal_roas(samples: dict, inputs: dict) -> pd.DataFrame:
    """
    Compute marginal ROAS for each channel × region at current spend levels.

    Marginal ROAS answers: "If I spend $1 more on this channel right now,
    how much additional revenue do I expect?"

    Derivation
    ----------
    Revenue contribution from channel c in region r:

        revenue_c = beta_c × Hill(adstock_norm_c ; k_c, ec_c)

    The marginal revenue per unit of *raw spend* is obtained via the chain rule:

        dRevenue/dSpend = beta_c × (dHill/dx) × (dx_norm/dSpend)

    where:
        dHill/dx     = k * ec^k * x^(k-1) / (x^k + ec^k)^2   [Hill derivative]
        dx_norm/dSpend ≈ 1 / p95_c                             [normalisation chain]
        x            = current normalised adstock

    The result is dollars of revenue per dollar of additional spend — marginal ROAS.

    Note: This is the *instantaneous* marginal ROAS at the current operating
    point, not the average ROAS. It will always be lower than average ROAS
    for channels operating in the diminishing returns region.

    We compute this for every posterior draw to get a full posterior
    distribution of marginal ROAS, then summarise with mean and 90% CI.
    """
    print("\n  Computing marginal ROAS...")

    ch_param = {
        "tv":          ("alpha_tv",   "k_tv",   "ec_tv",   "beta_tv"),
        "paid_search": ("alpha_ps",   "k_ps",   "ec_ps",   "beta_ps"),
        "social":      ("alpha_so",   "k_so",   "ec_so",   "beta_so"),
        "display":     ("alpha_disp", "k_disp", "ec_disp", "beta_disp"),
    }

    rows = []

    for r, region in enumerate(REGIONS):
        for ch in CHANNELS:
            a_key, k_key, ec_key, b_key = ch_param[ch]

            alpha_draws = samples[a_key][:, r]   # (D,)
            k_draws     = samples[k_key][:, r]
            ec_draws    = samples[ec_key][:, r]
            beta_draws  = samples[b_key][:, r]

            p95_val = inputs["p95"][ch][r]
            spend_r = inputs["spend"][ch][r]

            # For each draw, compute current adstock_norm using that draw's alpha
            # then evaluate the Hill derivative at that point.
            # Vectorising over draws is memory-intensive for large D; we batch.
            D = len(alpha_draws)
            marginal_roas_draws = np.empty(D, dtype=float)

            for d in range(D):
                ads_norm = compute_current_adstock_norm(
                    spend_r, float(alpha_draws[d]), p95_val
                )
                # Use mean normalised adstock as the "current operating point"
                x_current = float(ads_norm.mean())

                # Hill derivative at current x
                dhill_dx = hill_derivative_np(
                    np.array([x_current]),
                    k_draws[d],
                    ec_draws[d],
                )[0]

                # Marginal ROAS = beta × dHill/dx × (1/p95)
                marginal_roas_draws[d] = float(
                    beta_draws[d] * dhill_dx * (1.0 / p95_val)
                )

            mean_roas = float(marginal_roas_draws.mean())
            lo90      = float(np.percentile(marginal_roas_draws,  5))
            hi90      = float(np.percentile(marginal_roas_draws, 95))
            median    = float(np.median(marginal_roas_draws))

            rows.append({
                "region":          region,
                "channel":         ch,
                "marginal_roas_mean":   round(mean_roas, 3),
                "marginal_roas_median": round(median,    3),
                "marginal_roas_lo90":   round(lo90,      3),
                "marginal_roas_hi90":   round(hi90,      3),
            })

            print(f"    {REGION_LABELS[region]:>15s} | {CHANNEL_LABELS[ch]:>12s}: "
                  f"mROAS = {mean_roas:.2f}  "
                  f"[{lo90:.2f}, {hi90:.2f}] 90% CI")

    return pd.DataFrame(rows)


def plot_roas_uncertainty(roas_df: pd.DataFrame,
                           save_path: str = "outputs/fig_roas_uncertainty.png"):
    """
    Dot-and-whisker plot of marginal ROAS with 90% credible intervals.

    Layout: one panel per region, channels on y-axis, marginal ROAS on x-axis.
    This makes it easy to rank channels within a region and compare uncertainty.

    A marginal ROAS > 1 means the channel is generating more revenue than its
    marginal spend cost. A marginal ROAS < 1 suggests the channel is oversaturated
    at current spend levels and budget should be reallocated.
    """
    print("\n  Plotting ROAS uncertainty...")

    fig, axes = plt.subplots(1, N_REGIONS, figsize=(4 * N_REGIONS, 5), sharey=True)
    fig.suptitle(
        "MapleThread — Marginal ROAS at Current Spend Levels\n"
        "Dot = posterior mean  |  Whisker = 90% credible interval\n"
        "mROAS > 1: generating more revenue than marginal cost  |  "
        "mROAS < 1: channel oversaturated",
        fontsize=12, fontweight="bold",
    )

    for r, region in enumerate(REGIONS):
        ax    = axes[r]
        color = PALETTE[region]
        sub   = roas_df[roas_df["region"] == region].reset_index(drop=True)

        y_pos = np.arange(len(CHANNELS))

        for i, row in sub.iterrows():
            ch    = row["channel"]
            mean  = row["marginal_roas_mean"]
            lo90  = row["marginal_roas_lo90"]
            hi90  = row["marginal_roas_hi90"]

            ax.plot([lo90, hi90], [i, i], color=PALETTE[ch], lw=2.5, alpha=0.7)
            ax.scatter([mean], [i], color=PALETTE[ch], s=80, zorder=5)
            ax.text(hi90 + 0.02, i, f"{mean:.2f}", va="center",
                    fontsize=8, color=PALETTE[ch], fontweight="bold")

        ax.axvline(1.0, color="black", lw=1.2, linestyle="--",
                   alpha=0.6, label="mROAS = 1")
        ax.set_yticks(y_pos)
        ax.set_yticklabels([CHANNEL_LABELS[ch] for ch in CHANNELS], fontsize=9)
        ax.set_xlabel("Marginal ROAS", fontsize=9)
        ax.set_title(REGION_LABELS[region], fontsize=10,
                     fontweight="bold", color=color)
        ax.set_xlim(left=0)

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ ROAS uncertainty plot saved: {save_path}")


