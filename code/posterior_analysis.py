def build_roas_summary_table(roas_df: pd.DataFrame,
                              contrib_df: pd.DataFrame,
                              save_path: str = "outputs/roas_summary.csv") -> pd.DataFrame:
    """
    Merge marginal ROAS and contribution share into a single summary table.

    Columns
    -------
    region, channel,
    mean_share_pct, lo90_share_pct, hi90_share_pct   ← contribution as % revenue
    marginal_roas_mean, marginal_roas_lo90, hi90      ← marginal ROAS

    This table is the primary input to Phase 6 budget optimisation. Channels
    with high marginal ROAS and low contribution share are underfunded.
    Channels with low marginal ROAS and high contribution share are saturated.
    """
    merged = roas_df.merge(contrib_df, on=["region", "channel"], how="left")

    # Reorder columns for readability
    col_order = [
        "region", "channel",
        "mean_share_pct", "lo90_share_pct", "hi90_share_pct",
        "marginal_roas_mean", "marginal_roas_median",
        "marginal_roas_lo90", "marginal_roas_hi90",
    ]
    merged = merged[col_order]

    merged.to_csv(save_path, index=False)
    print(f"\n  ✓ ROAS summary table saved: {save_path}")

    # Print a formatted view
    print("\n  ── ROAS Summary Table ──")
    print(f"  {'Region':<15} {'Channel':<12} {'Share%':>7} "
          f"{'mROAS':>7} {'90% CI':>15}")
    print("  " + "─" * 62)
    for _, row in merged.iterrows():
        print(f"  {REGION_LABELS[row['region']]:<15} "
              f"{CHANNEL_LABELS[row['channel']]:<12} "
              f"{row['mean_share_pct']:>6.1f}%  "
              f"{row['marginal_roas_mean']:>6.2f}   "
              f"[{row['marginal_roas_lo90']:.2f}, {row['marginal_roas_hi90']:.2f}]")

    return merged


