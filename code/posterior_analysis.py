def plot_contribution_bars(samples: dict,
                            inputs: dict,
                            save_path: str = "outputs/fig_contribution_bars.png"):
    """
    Bar chart of total channel contribution as % of total revenue, with
    90% credible intervals.

    For each posterior draw d, we compute:
        share_{ch,r,d} = sum_t(contrib_{ch,r,d,t}) / sum_t(revenue_{r,t})

    The posterior distribution of this share gives us probabilistic attribution.

    Layout: one panel per region, grouped bars per channel.
    Error bars are 5th–95th percentile (90% credible interval).
    """
    print("\n  Plotting contribution bar chart...")

    fig, axes = plt.subplots(1, N_REGIONS, figsize=(4 * N_REGIONS, 6), sharey=False)
    fig.suptitle(
        "MapleThread — Channel Revenue Attribution\n"
        "Bar = posterior mean % of total revenue  |  Error bar = 90% credible interval",
        fontsize=13, fontweight="bold",
    )

    summary_rows = []

    for r, region in enumerate(REGIONS):
        ax    = axes[r]
        color = PALETTE[region]

        total_obs_revenue = inputs["revenue"][r].sum()   # scalar

        means = []
        lo90  = []
        hi90  = []
        ch_labels = []

        for ch in CHANNELS:
            contrib_draws = samples[f"contrib_{ch}_{region}"]   # (D, T)
            # Total contribution per draw as % of observed revenue
            share_draws = contrib_draws.sum(axis=1) / total_obs_revenue * 100

            m  = float(share_draws.mean())
            lo = float(np.percentile(share_draws,  5))
            hi = float(np.percentile(share_draws, 95))

            means.append(m)
            lo90.append(m - lo)
            hi90.append(hi - m)
            ch_labels.append(CHANNEL_LABELS[ch])

            summary_rows.append({
                "region":  region,
                "channel": ch,
                "mean_share_pct":  round(m,  2),
                "lo90_share_pct":  round(lo, 2),
                "hi90_share_pct":  round(hi, 2),
            })

        x_pos = np.arange(len(CHANNELS))
        bars  = ax.bar(x_pos, means,
                       color=[PALETTE[ch] for ch in CHANNELS],
                       alpha=0.82, width=0.6, zorder=3)
        ax.errorbar(x_pos, means, yerr=[lo90, hi90],
                    fmt="none", color="black", capsize=5,
                    elinewidth=1.5, capthick=1.5, zorder=4)

        ax.set_xticks(x_pos)
        ax.set_xticklabels(ch_labels, fontsize=9, rotation=20, ha="right")
        ax.set_ylabel("% of total revenue" if r == 0 else "", fontsize=9)
        ax.set_title(REGION_LABELS[region], fontsize=10, fontweight="bold", color=color)
        ax.set_ylim(0, max(means) * 1.5)

        for bar, m in zip(bars, means):
            ax.text(bar.get_x() + bar.get_width() / 2, m + 0.3,
                    f"{m:.1f}%", ha="center", va="bottom", fontsize=7.5,
                    fontweight="bold")

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Contribution bars saved: {save_path}")

    return pd.DataFrame(summary_rows)


