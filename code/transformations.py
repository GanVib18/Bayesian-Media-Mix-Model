# 5. MARGINAL ROAS UTILITY
# ══════════════════════════════════════════════════════════════════════════════

def hill_derivative(x: float | np.ndarray, k: float, ec: float) -> np.ndarray:
    """
    Analytical derivative of the Hill function with respect to x.

    Used to compute marginal ROAS at current spend levels (Phase 5):

        dS/dx = k * ec^k * x^(k-1) / (x^k + ec^k)^2

    Parameters
    ----------
    x : float or np.ndarray
        Input spend level (normalised adstock). Should be > 0.
    k : float
        Hill slope parameter.
    ec : float
        Hill half-saturation point.

    Returns
    -------
    np.ndarray
        Marginal effect per unit of normalised adstock at each point in x.

    Notes
    -----
    To convert to marginal revenue (approximate ROAS), multiply the result
    by beta / p95, where beta is the channel coefficient and p95 is the
    normalisation constant used in adstock scaling.
    """
    x = np.asarray(x, dtype=float)
    safe_x = np.where(x <= 0, 1e-10, x)
    numerator   = k * (ec**k) * (safe_x ** (k - 1))
    denominator = (safe_x**k + ec**k) ** 2
    return np.where(x <= 0, 0.0, numerator / denominator)

