class TestGeometricAdstock:

    def test_single_pulse_decays_correctly(self):
        """A single spend impulse should decay geometrically."""
        spend = np.zeros(5)
        spend[0] = 100.0
        result = geometric_adstock(spend, alpha=0.5)
        expected = np.array([100.0, 50.0, 25.0, 12.5, 6.25])
        np.testing.assert_allclose(result, expected, rtol=1e-6)

    def test_zero_alpha_no_carryover(self):
        """alpha=0 means adstock equals raw spend (no carryover)."""
        spend = np.array([10.0, 20.0, 30.0, 0.0, 50.0])
        result = geometric_adstock(spend, alpha=0.0)
        np.testing.assert_allclose(result, spend, rtol=1e-10)

    def test_output_length_preserved(self):
        result = geometric_adstock(SPEND_RANDOM, alpha=0.5)
        assert result.shape == SPEND_RANDOM.shape

    def test_zero_spend_returns_zeros(self):
        result = geometric_adstock(SPEND_ZEROS, alpha=0.7)
        np.testing.assert_allclose(result, 0.0, atol=1e-10)

    def test_high_alpha_accumulates(self):
        """High alpha should produce values well above the raw spend."""
        spend = np.full(20, 100.0)
        result = geometric_adstock(spend, alpha=0.9)
        # At steady state, adstock ≈ spend / (1 - alpha) = 1000
        assert result[-1] > 500.0, "High alpha adstock should accumulate significantly."

    def test_steady_state_value(self):
        """At steady-state, adstock = spend / (1 - alpha)."""
        spend = np.full(200, 100.0)
        alpha = 0.75
        result = geometric_adstock(spend, alpha=alpha)
        expected_ss = 100.0 / (1 - alpha)
        np.testing.assert_allclose(result[-1], expected_ss, rtol=1e-3)

    def test_normalise_flag_produces_unit_scale(self):
        """normalise=True should put the 95th percentile at 1.0."""
        result = geometric_adstock(SPEND_RANDOM, alpha=0.5, normalise=True)
        p95 = np.percentile(result, 95)
        np.testing.assert_allclose(p95, 1.0, rtol=1e-6)

    def test_non_negative_output(self):
        result = geometric_adstock(SPEND_RANDOM, alpha=0.45)
        assert np.all(result >= 0), "Adstock must be non-negative."

    def test_invalid_alpha_raises(self):
        with pytest.raises(ValueError, match="alpha"):
            geometric_adstock(SPEND_RANDOM, alpha=1.0)
        with pytest.raises(ValueError, match="alpha"):
            geometric_adstock(SPEND_RANDOM, alpha=-0.1)

    def test_negative_spend_raises(self):
        bad_spend = np.array([100.0, -50.0, 200.0])
        with pytest.raises(ValueError, match="negative"):
            geometric_adstock(bad_spend, alpha=0.5)

    @pytest.mark.parametrize("alpha", [0.15, 0.20, 0.45, 0.75])
    def test_mapplethread_channels(self, alpha):
        """All four MapleThread decay rates should run without error."""
        result = geometric_adstock(SPEND_RANDOM, alpha=alpha)
        assert result.shape == SPEND_RANDOM.shape
        assert np.all(np.isfinite(result))

    def test_dtype_float(self):
        spend_int = np.array([100, 200, 300], dtype=int)
        result = geometric_adstock(spend_int, alpha=0.5)
        assert result.dtype == float


