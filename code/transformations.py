class TestHillDerivative:

    def test_non_negative_output(self):
        """Derivative of a monotone increasing function must be >= 0."""
        x = np.linspace(0, 5, 100)
        result = hill_derivative(x, k=2.0, ec=0.5)
        assert np.all(result >= 0)

    def test_zero_at_zero_x(self):
        """At x=0, derivative should be 0 (no spend → no marginal effect)."""
        result = hill_derivative(np.array([0.0]), k=2.0, ec=0.5)
        np.testing.assert_allclose(result[0], 0.0, atol=1e-8)

    def test_derivative_decreasing_past_inflection(self):
        """Past the inflection point, the derivative should be decreasing (diminishing returns)."""
        x = np.linspace(1.0, 10.0, 100)
        result = hill_derivative(x, k=2.0, ec=0.5)
        # All diffs should be negative in this region
        assert np.all(np.diff(result) < 0)

    def test_consistent_with_numerical_gradient(self):
        """Analytical derivative should match numerical gradient closely."""
        x = np.linspace(0.1, 3.0, 50)
        k, ec = 2.0, 0.5
        eps = 1e-6
        numerical = (hill_saturation(x + eps, k, ec) - hill_saturation(x - eps, k, ec)) / (2 * eps)
        analytical = hill_derivative(x, k, ec)
        np.testing.assert_allclose(analytical, numerical, rtol=1e-4)

    def test_output_finite(self):
        x = np.linspace(0, 5, 200)
        result = hill_derivative(x, k=2.5, ec=0.4)
        assert np.all(np.isfinite(result))