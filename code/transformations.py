class TestHillSaturation:

    def test_output_range_bounded(self):
        """Hill output must always be in (0, 1]."""
        x = np.linspace(0, 10, 1000)
        result = hill_saturation(x, k=2.0, ec=0.5)
        assert np.all(result >= 0), "Hill output must be >= 0."
        assert np.all(result <= 1.0 + 1e-10), "Hill output must be <= 1."

    def test_half_saturation_at_ec(self):
        """At x = ec, Hill function must return exactly 0.5."""
        for k, ec in [(1.5, 0.6), (2.5, 0.4), (3.0, 0.3), (1.2, 0.7)]:
            result = hill_saturation(np.array([ec]), k=k, ec=ec)
            np.testing.assert_allclose(result, 0.5, rtol=1e-6,
                err_msg=f"Hill(ec) != 0.5 for k={k}, ec={ec}")

    def test_asymptote_at_large_x(self):
        """Hill function should approach 1 asymptotically."""
        x = np.array([1e6])
        result = hill_saturation(x, k=2.0, ec=0.5)
        np.testing.assert_allclose(result, 1.0, rtol=1e-4)

    def test_zero_spend_approaches_zero(self):
        """Hill function at x=0 should return ~0 (no spend, no effect)."""
        result = hill_saturation(np.array([0.0]), k=2.0, ec=0.5)
        assert result[0] < 1e-8

    def test_monotone_increasing(self):
        """Hill function must be monotonically non-decreasing."""
        x = np.linspace(0, 5, 500)
        result = hill_saturation(x, k=2.5, ec=0.4)
        diffs = np.diff(result)
        assert np.all(diffs >= -1e-10), "Hill function must be monotonically increasing."

    def test_higher_k_sharper_curve(self):
        """
        Higher k should produce a sharper S-curve: at x < ec, lower response;
        at x > ec (well above), higher response — compared to lower k.
        """
        x_below = np.array([0.1])
        low_k  = hill_saturation(x_below, k=1.2, ec=0.4)
        high_k = hill_saturation(x_below, k=3.0, ec=0.4)
        # At x << ec, higher k gives lower response (more convex initial phase)
        assert low_k[0] > high_k[0], "Higher k should give lower effect below ec."

    def test_output_length_preserved(self):
        x = np.linspace(0, 2, 100)
        result = hill_saturation(x, k=2.0, ec=0.5)
        assert result.shape == x.shape

