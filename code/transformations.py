# 3. HILL SATURATION
# ══════════════════════════════════════════════════════════════════════════════

def hill_saturation(
    x: np.ndarray,
    k: float,
    ec: float,
) -> np.ndarray:
    """
    Hill saturation (diminishing-returns) function.

    Maps any non-negative input to the interval (0, 1], encoding the empirical
    observation that media returns diminish as spend increases:

        S(x) = x^k / (x^k + ec^k)

    At x = ec, S = 0.5 exactly — ec is the "half-saturation point", the spend
    level at which you achieve half the theoretical maximum effect.

    Shape intuition
    ---------------
    k (slope / Hill coefficient):
        k < 1 : concave from the start — diminishing returns immediately.
        k = 1 : hyperbolic (Michaelis–Menten) saturation.
        k > 1 : sigmoid / S-curve with an initial convex phase before
                diminishing returns kick in. Higher k = sharper transition.
    ec (half-saturation):
        Smaller ec = faster saturation (channel reaches diminishing returns at
        lower spend levels). Larger ec = more room to grow before saturation.

    MapleThread ground-truth parameters (for reference):
        TV          : k=2.5, ec=0.4  → strong S-curve, saturates quickly
        Paid Search : k=1.5, ec=0.6  → moderate sigmoid
        Social      : k=1.2, ec=0.7  → mild curvature, room to grow
        Display     : k=3.0, ec=0.3  → very sharp S-curve, saturates fast

    Parameters
    ----------
    x : np.ndarray
        Input values (normalised adstock). All values should be >= 0. Typically
        in [0, ~1.5] after 95th-percentile normalisation.
    k : float
        Hill slope parameter (> 0). Controls curvature.
    ec : float
        Half-saturation point (> 0). At x = ec, output = 0.5.

    Returns
    -------
    np.ndarray
        Saturation-adjusted effect, values in (0, 1].

    Examples
    --------
    >>> hill_saturation(np.array([0.0, 0.4, 1.0, 2.0]), k=2.0, ec=0.5)
    array([0.        , 0.39024390, 0.8       , 0.94117647])
    """
    if k <= 0:
        raise ValueError(f"k must be > 0, got {k!r}")
    if ec <= 0:
        raise ValueError(f"ec must be > 0, got {ec!r}")

    x = np.asarray(x, dtype=float)
    # Avoid 0^k = 0 / 0 ambiguity at x=0: result is correctly 0 (no spend → no effect)
    safe_x = np.where(x == 0.0, 1e-10, x)
    return safe_x**k / (safe_x**k + ec**k)


