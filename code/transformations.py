# 4. FULL PIPELINE: ADSTOCK → NORMALISE → HILL
# ══════════════════════════════════════════════════════════════════════════════

def transform_spend(
    spend: np.ndarray,
    alpha: float,
    k: float,
    ec: float,
    *,
    normalise_percentile: float = 95.0,
    use_weibull: bool = False,
    weibull_shape: float | None = None,
    weibull_scale: float | None = None,
    weibull_max_lag: int = 13,
) -> dict[str, np.ndarray]:
    """
    Full media transformation pipeline matching the MapleThread DGP.

    Applies in sequence:
        1. Adstock (geometric or Weibull) → captures carryover
        2. Normalisation by `normalise_percentile` percentile → [0, ~1]
        3. Hill saturation → diminishing returns in [0, 1]

    This function is the canonical transformation used in both data generation
    and model construction, ensuring consistency between the two.

    Parameters
    ----------
    spend : np.ndarray, shape (T,)
        Raw media spend for one channel.
    alpha : float
        Geometric adstock decay rate in [0, 1). Ignored if use_weibull=True.
    k : float
        Hill slope parameter (> 0).
    ec : float
        Hill half-saturation point (> 0).
    normalise_percentile : float, optional
        Percentile for adstock normalisation. Default: 95.0 (matches DGP).
    use_weibull : bool, optional
        If True, use Weibull adstock instead of geometric. Requires
        weibull_shape and weibull_scale. Default: False.
    weibull_shape : float, optional
        Weibull shape parameter. Required when use_weibull=True.
    weibull_scale : float, optional
        Weibull scale parameter. Required when use_weibull=True.
    weibull_max_lag : int, optional
        Maximum lag window for Weibull convolution. Default: 13.

    Returns
    -------
    dict with keys:
        "adstock"      : np.ndarray — raw adstock (before normalisation)
        "adstock_norm" : np.ndarray — normalised adstock (input to Hill)
        "saturated"    : np.ndarray — Hill-transformed output in [0, 1]

    Examples
    --------
    >>> spend = np.random.default_rng(0).lognormal(10, 0.3, 52)
    >>> result = transform_spend(spend, alpha=0.75, k=2.5, ec=0.4)
    >>> result["saturated"].shape
    (52,)
    """
    if use_weibull:
        if weibull_shape is None or weibull_scale is None:
            raise ValueError(
                "weibull_shape and weibull_scale must be provided when use_weibull=True."
            )
        adstock = weibull_adstock(
            spend,
            shape=weibull_shape,
            scale=weibull_scale,
            max_lag=weibull_max_lag,
        )
    else:
        adstock = geometric_adstock(spend, alpha)

    p = np.percentile(adstock, normalise_percentile)
    adstock_norm = adstock / p if p > 0 else adstock.copy()

    saturated = hill_saturation(adstock_norm, k, ec)

    return {
        "adstock":      adstock,
        "adstock_norm": adstock_norm,
        "saturated":    saturated,
    }


