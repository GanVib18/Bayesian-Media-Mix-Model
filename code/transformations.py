# 1. GEOMETRIC ADSTOCK
# ══════════════════════════════════════════════════════════════════════════════

def geometric_adstock(
    spend: np.ndarray,
    alpha: float,
    *,
    normalise: bool = False,
    normalise_percentile: float = 95.0,
) -> np.ndarray:
    """
    Geometric (exponential) adstock transformation.

    Each period's adstock is current spend plus alpha times the previous
    adstock value, forming a recursive convolution:

        adstock[0] = spend[0]
        adstock[t] = spend[t] + alpha * adstock[t-1]   for t >= 1

    The result is an impressionistic memory of past spend: high alpha values
    (e.g. 0.75 for TV) create a long tail of carryover; low values (e.g. 0.15
    for Display) decay almost immediately.

    Parameters
    ----------
    spend : np.ndarray, shape (T,)
        Raw media spend time series. All values should be >= 0.
    alpha : float
        Decay rate in [0, 1). 0 = no carryover; values close to 1 = very long
        memory. Typical range:
            TV           ~ 0.70–0.80  (brand-building, long carryover)
            Social       ~ 0.40–0.55  (medium carryover)
            Paid Search  ~ 0.15–0.25  (mostly immediate demand capture)
            Display      ~ 0.10–0.20  (very short carryover)
    normalise : bool, optional
        If True, divide the resulting adstock by its `normalise_percentile`
        percentile, rescaling to a [0, ~1] range. Useful before Hill
        saturation so the ec parameter is interpretable on a 0–1 scale.
        Default: False.
    normalise_percentile : float, optional
        Percentile used for normalisation. Default: 95.0, matching the DGP.

    Returns
    -------
    np.ndarray, shape (T,)
        Adstock series (same length as spend). Normalised to [0, ~1] if
        `normalise=True`.

    Notes
    -----
    PyMC compatibility: replace the Python for-loop with pytensor.scan when
    embedding this inside a pm.Model for vectorised gradient computation.

    Examples
    --------
    >>> spend = np.array([100., 0., 0., 0., 0.])
    >>> geometric_adstock(spend, alpha=0.5)
    array([100.  ,  50.  ,  25.  ,  12.5 ,   6.25])
    """
    if not (0.0 <= alpha < 1.0):
        raise ValueError(f"alpha must be in [0, 1), got {alpha!r}")
    if np.any(spend < 0):
        raise ValueError("spend contains negative values; all entries must be >= 0.")

    spend = np.asarray(spend, dtype=float)
    adstock = np.empty_like(spend)
    adstock[0] = spend[0]
    for t in range(1, len(spend)):
        adstock[t] = spend[t] + alpha * adstock[t - 1]

    if normalise:
        p = np.percentile(adstock, normalise_percentile)
        if p > 0:
            adstock = adstock / p

    return adstock


