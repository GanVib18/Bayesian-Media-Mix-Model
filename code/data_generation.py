# ── Figure 5: Channel Contribution Decomposition ──────────────────────────────

def plot_contributions(gt_df: pd.DataFrame, save_path: str = "outputs/fig_contributions.png"):
    fig, axes = plt.subplots(5, 1, figsize=(16, 18), sharex=False)
    fig.suptitle(
        "MapleThread — True Channel Revenue Contributions (Ground Truth)\n"
        "Stacked area = total explained revenue | Remaining gap = baseline demand",
        fontsize=13, fontweight="bold", y=1.01,
    )
    for ax, region in zip(axes, REGIONS):
        df = gt_df[gt_df["region"] == region].copy().reset_index(drop=True)
        dates    = pd.to_datetime(df["date"])
        baseline = df["true_baseline"].values
        revenue  = df["true_revenue"].values
        contribs = np.column_stack([df[f"contrib_{ch}"].values for ch in CHANNELS])

        ax.fill_between(dates, 0, baseline, alpha=0.4, color=PALETTE["baseline"], label="Baseline")
        bottom = baseline.copy()
        for i, ch in enumerate(CHANNELS):
            top = bottom + contribs[:, i]
            ax.fill_between(dates, bottom, top, alpha=0.75,
                            color=PALETTE[ch], label=CHANNEL_LABELS[ch])
            bottom = top
        ax.plot(dates, revenue, color="white", lw=0.8, alpha=0.5)
        ax.set_title(REGION_LABELS[region], fontsize=11, fontweight="bold")
        ax.set_ylabel("Revenue ($)")
        ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
        ax.legend(loc="upper left", fontsize=8, ncol=3, framealpha=0.7)
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Contributions saved: {save_path}")


