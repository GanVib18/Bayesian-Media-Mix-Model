# ── Transformations ──────────────────────────────────────────────────────────

def geometric_adstock(spend: np.ndarray, alpha: float) -> np.ndarray:
    """Geometric adstock: adstock[t] = spend[t] + alpha * adstock[t-1]"""
    adstock = np.zeros_like(spend, dtype=float)
    adstock[0] = spend[0]
    for t in range(1, len(spend)):
        adstock[t] = spend[t] + alpha * adstock[t - 1]
    return adstock


def hill_saturation(x: np.ndarray, k: float, ec: float) -> np.ndarray:
    """Hill saturation: S(x) = x^k / (x^k + ec^k) → returns value in [0, 1]"""
    x = np.where(x == 0, 1e-10, x)
    return x ** k / (x ** k + ec ** k)


def build_time_index(n_weeks: int, start_date: str = "2021-01-04") -> pd.DatetimeIndex:
    return pd.date_range(start=start_date, periods=n_weeks, freq="W-MON")


# ── Step 1: Baseline Demand ───────────────────────────────────────────────────

def generate_baseline(region: str, n_weeks: int, rng: np.random.Generator) -> np.ndarray:
    params = BASELINE[region]
    t = np.arange(n_weeks)
    week_of_year = (t % 52) + 1

    trend = params["intercept"] + params["trend_slope"] * t

    amps = params["seasonality_amplitudes"]
    seasonality = (
        amps[0] * np.sin(2 * np.pi * t / 52) +
        amps[1] * np.cos(2 * np.pi * t / 52) +
        amps[2] * np.sin(4 * np.pi * t / 52) +
        amps[3] * np.cos(4 * np.pi * t / 52)
    )

    holiday_multiplier = np.ones(n_weeks)
    for (holiday_week, lift, _label) in HOLIDAY_SPIKES:
        mask = (week_of_year == holiday_week)
        holiday_multiplier[mask] = lift

    baseline_signal = (trend + seasonality) * holiday_multiplier
    noise = rng.normal(0, params["noise_std"], n_weeks)
    return np.maximum(baseline_signal + noise, 0)


# ── Step 2: Raw Spend Generation ─────────────────────────────────────────────

def _is_promo_week(week_of_year: int) -> bool:
    for (start, duration, _label) in PROMO_CALENDAR:
        if start <= week_of_year < start + duration:
            return True
    return False


def generate_spend(region: str, channel: str, n_weeks: int, rng: np.random.Generator) -> np.ndarray:
    config = SPEND_CONFIG[region][channel]
    base       = config["base_spend"]
    var_scale  = config["variance_scale"]
    growth     = config["growth_rate"]
    burst_mult = config["burst_multiplier"]

    t = np.arange(n_weeks)
    week_of_year = (t % 52) + 1

    log_mean = np.log(base) - 0.5 * var_scale ** 2
    spend = rng.lognormal(log_mean, var_scale, n_weeks)
    spend = spend * (1 + growth) ** t

    for i, woy in enumerate(week_of_year):
        if _is_promo_week(woy):
            spend[i] *= burst_mult

    return np.maximum(spend, 0)


# ── Steps 3 & 4: Adstock + Hill Saturation ───────────────────────────────────

def transform_spend(spend: np.ndarray, channel: str) -> tuple:
    alpha = ADSTOCK_PARAMS[channel]["alpha"]
    k     = HILL_PARAMS[channel]["k"]
    ec    = HILL_PARAMS[channel]["ec"]

    adstock = geometric_adstock(spend, alpha)

    p95 = np.percentile(adstock, 95)
    adstock_norm = adstock / p95 if p95 > 0 else adstock

    saturated = hill_saturation(adstock_norm, k, ec)
    return adstock, saturated


# ── Step 5: Revenue Assembly ──────────────────────────────────────────────────

def compute_revenue(baseline: np.ndarray, saturated_effects: dict, region: str) -> tuple:
    betas = CHANNEL_COEFFICIENTS[region]
    contributions = {}
    channel_sum = np.zeros_like(baseline)

    for channel, effect in saturated_effects.items():
        contribution = betas[channel] * effect
        contributions[channel] = contribution
        channel_sum += contribution

    revenue = baseline + channel_sum
    return revenue, contributions


# ── Main: Full Dataset ────────────────────────────────────────────────────────

def generate_full_dataset() -> tuple:
    rng   = np.random.default_rng(RANDOM_SEED)
    dates = build_time_index(N_WEEKS)

    raw_rows, gt_rows = [], []

    for region in REGIONS:
        print(f"  Generating: {region}...")

        baseline = generate_baseline(region, N_WEEKS, rng)

        raw_spends, adstocks, saturated_effects = {}, {}, {}
        for channel in CHANNELS:
            raw_spend = generate_spend(region, channel, N_WEEKS, rng)
            adstock, saturated = transform_spend(raw_spend, channel)
            raw_spends[channel]        = raw_spend
            adstocks[channel]          = adstock
            saturated_effects[channel] = saturated

        revenue, contributions = compute_revenue(baseline, saturated_effects, region)

        for i, date in enumerate(dates):
            raw_row = {
                "date":         date,
                "region":       region,
                "revenue":      revenue[i],
                "week_of_year": date.isocalendar().week,
                "year":         date.year,
                "t":            i,
            }
            for ch in CHANNELS:
                raw_row[f"spend_{ch}"] = raw_spends[ch][i]
            raw_rows.append(raw_row)

            gt_row = {
                "date":          date,
                "region":        region,
                "true_baseline": baseline[i],
                "true_revenue":  revenue[i],
            }
            for ch in CHANNELS:
                gt_row[f"contrib_{ch}"]   = contributions[ch][i]
                gt_row[f"adstock_{ch}"]   = adstocks[ch][i]
                gt_row[f"saturated_{ch}"] = saturated_effects[ch][i]
            gt_rows.append(gt_row)

    return pd.DataFrame(raw_rows), pd.DataFrame(gt_rows)


