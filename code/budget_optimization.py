# 5. POSTERIOR OPTIMISATION (main loop)
# ══════════════════════════════════════════════════════════════════════════════

def run_posterior_optimisation(samples:       dict,
                                p95_constants: dict,
                                current_budgets: dict,
                                budget_multiplier: float = 1.0) -> dict:
    """
    Run budget optimisation across all posterior draws for all regions.

    For each draw d and region r, we:
      1. Extract per-channel parameters (alpha, k, ec, beta).
      2. Define the total budget = budget_multiplier × current_total_spend[r].
      3. Define per-channel bounds = [10% current, 300% current] (capped at budget).
      4. Call optimise_single_draw to get optimal spend allocation.
      5. Compute predicted revenue at optimal vs. current allocation.

    Returns
    -------
    dict: region → {
        "optimal_spend":    (n_draws, C) — optimal spend per draw
        "optimal_revenue":  (n_draws,)   — predicted media revenue at optimal
        "current_revenue":  (n_draws,)   — predicted media revenue at current
        "revenue_uplift":   (n_draws,)   — optimal - current (absolute)
        "pct_uplift":       (n_draws,)   — uplift as % of current
        "current_spend":    (C,)         — mean current spend per channel
        "total_budget":     float        — total budget used
    }
    """
    ch_param_keys = {
        "tv":          ("alpha_tv",   "k_tv",   "ec_tv",   "beta_tv"),
        "paid_search": ("alpha_ps",   "k_ps",   "ec_ps",   "beta_ps"),
        "social":      ("alpha_so",   "k_so",   "ec_so",   "beta_so"),
        "display":     ("alpha_disp", "k_disp", "ec_disp", "beta_disp"),
    }

    n_draws = next(iter(samples.values())).shape[0]
    results = {}

    for r, region in enumerate(REGIONS):
        current_spend = np.array([
            current_budgets[region][ch] for ch in CHANNELS
        ])
        total_budget = float(current_spend.sum() * budget_multiplier)

        # Per-channel bounds: [10% current, 300% current], clipped to total_budget
        spend_bounds = [
            (max(0.10 * current_spend[c], 1.0),
             min(3.00 * current_spend[c], total_budget * 0.9))
            for c in range(N_CHANNELS)
        ]

        p95_vec = np.array([p95_constants[ch][r] for ch in CHANNELS])

        optimal_spend   = np.zeros((n_draws, N_CHANNELS))
        optimal_revenue = np.zeros(n_draws)
        current_revenue = np.zeros(n_draws)

        for d in range(n_draws):
            alpha_vec = np.array([
                float(samples[ch_param_keys[ch][0]][d, r]) for ch in CHANNELS
            ])
            k_vec = np.array([
                float(samples[ch_param_keys[ch][1]][d, r]) for ch in CHANNELS
            ])
            ec_vec = np.array([
                float(samples[ch_param_keys[ch][2]][d, r]) for ch in CHANNELS
            ])
            beta_vec = np.array([
                float(samples[ch_param_keys[ch][3]][d, r]) for ch in CHANNELS
            ])

            opt_spend = optimise_single_draw(
                alpha_vec, k_vec, ec_vec, beta_vec, p95_vec,
                current_spend, total_budget, spend_bounds,
            )

            opt_rev  = predict_revenue(opt_spend,    alpha_vec, k_vec, ec_vec, beta_vec, p95_vec)
            curr_rev = predict_revenue(current_spend, alpha_vec, k_vec, ec_vec, beta_vec, p95_vec)

            optimal_spend[d]   = opt_spend
            optimal_revenue[d] = opt_rev
            current_revenue[d] = curr_rev

        revenue_uplift = optimal_revenue - current_revenue
        pct_uplift     = revenue_uplift / (current_revenue + 1e-8) * 100

        results[region] = {
            "optimal_spend":   optimal_spend,
            "optimal_revenue": optimal_revenue,
            "current_revenue": current_revenue,
            "revenue_uplift":  revenue_uplift,
            "pct_uplift":      pct_uplift,
            "current_spend":   current_spend,
            "total_budget":    total_budget,
        }

        mean_uplift = float(revenue_uplift.mean())
        mean_pct    = float(pct_uplift.mean())
        print(f"    {REGION_LABELS[region]:>15s}: "
              f"mean uplift = ${mean_uplift:>8,.0f}/wk  "
              f"({mean_pct:+.1f}%)")

    return results


