def load_idata(path: str = "idata_hierarchical.nc") -> az.InferenceData:
    """Load Phase 4 InferenceData."""
    print(f"  Loading InferenceData from {path}...")
    idata = az.from_netcdf(path)
    chains = idata.posterior.dims["chain"]
    draws  = idata.posterior.dims["draw"]
    print(f"  Chains: {chains}  Draws: {draws}  Total: {chains * draws}")
    return idata


def load_raw_data(path: str = "synthetic_raw.csv") -> pd.DataFrame:
    """Load raw spend data to compute current budgets."""
    raw_df = pd.read_csv(path, parse_dates=["date"])
    print(f"  Loaded {len(raw_df)} rows from {path}.")
    return raw_df


def compute_current_budgets(raw_df: pd.DataFrame) -> dict:
    """
    Compute mean weekly spend per channel per region from the raw data.

    This is the "current budget" the optimiser will constrain against.
    Using the mean over 156 weeks gives a representative steady-state
    spend level that matches the steady-state revenue model assumption.

    Returns
    -------
    dict: region → {channel: mean_weekly_spend}
    """
    budgets = {}
    for region in REGIONS:
        df = raw_df[raw_df["region"] == region]
        budgets[region] = {
            ch: float(df[f"spend_{ch}"].mean()) for ch in CHANNELS
        }
    return budgets


def compute_p95_constants(raw_df: pd.DataFrame) -> dict:
    """
    Recompute p95 normalisation constants — identical to Phase 4/5.

    Returns
    -------
    dict: {channel: np.ndarray of shape (R,)}
    """
    lags = np.arange(MAX_LAG, dtype=float)
    p95  = {ch: [] for ch in CHANNELS}

    for region in REGIONS:
        df = raw_df[raw_df["region"] == region].reset_index(drop=True)
        for ch in CHANNELS:
            spend = df[f"spend_{ch}"].values.astype(float)
            T     = len(spend)
            lag_mat = np.zeros((T, MAX_LAG), dtype=float)
            for l in range(MAX_LAG):
                lag_mat[l:, l] = spend[:T - l]
            weights  = TRUE_ALPHAS[ch] ** lags
            ads_true = lag_mat @ weights
            p95[ch].append(float(np.percentile(ads_true, 95)))

    return {ch: np.array(p95[ch]) for ch in CHANNELS}   # (R,)


def extract_posterior_samples(idata: az.InferenceData,
                               n_draws: int = N_OPT_DRAWS) -> dict:
    """
    Extract and subsample posterior draws for optimisation.

    We subsample to `n_draws` to keep optimisation tractable. Draws are
    selected with a fixed random seed for reproducibility. Using 500 draws
    gives stable results — the distribution of optimal allocations converges
    well before 4000 draws.

    Returns
    -------
    dict: param_name → np.ndarray of shape (n_draws, R)
    """
    posterior = idata.posterior
    chains    = posterior.dims["chain"]
    draws     = posterior.dims["draw"]
    D         = chains * draws

    rng     = np.random.default_rng(RANDOM_SEED)
    indices = rng.choice(D, size=min(n_draws, D), replace=False)

    per_region_params = [
        "alpha_tv",   "alpha_ps",   "alpha_so",   "alpha_disp",
        "k_tv",       "k_ps",       "k_so",       "k_disp",
        "ec_tv",      "ec_ps",      "ec_so",      "ec_disp",
        "beta_tv",    "beta_ps",    "beta_so",    "beta_disp",
    ]

    samples = {}
    for p in per_region_params:
        if p in posterior:
            arr = posterior[p].values.reshape(D, N_REGIONS)
            samples[p] = arr[indices]   # (n_draws, R)

    print(f"  Extracted {len(indices)} posterior draws for optimisation.")
    return samples


