"""
budget_optimisation.py
======================
MapleThread Outdoor Co. — MMM Phase 6: Budget Optimisation

Turns the Phase 4 hierarchical posterior into a decision tool. For each region,
we find the budget allocation across channels that maximises expected revenue,
subject to a total budget constraint equal to current spend.

Approach
--------
For each posterior draw we have a complete set of channel parameters (alpha, k,
ec, beta). We treat these as the "true" parameters for that draw and solve a
constrained optimisation over the budget allocation vector using SciPy SLSQP.
Collecting optimal allocations across all draws gives us a posterior distribution
over the optimal budget — an honest recommendation with quantified uncertainty.

We also run this across a range of total budget scenarios (50%–200% of current)
to produce budget response curves: how does optimal revenue change as total
budget increases?

Revenue model used in optimiser (per channel c, single-period approximation)
-----------------------------------------------------------------------------
    adstock_c(s_c) ≈ s_c / (1 - alpha_c)      [steady-state geometric adstock]
    adstock_norm_c = adstock_c / p95_c
    saturation_c   = Hill(adstock_norm_c; k_c, ec_c)
    contribution_c = beta_c × saturation_c

The steady-state approximation treats each week as a representative period with
constant spend s_c, giving a clean closed-form that is differentiable and fast
to optimise. This is standard practice in MMM budget tools.

Sections
--------
  1. Imports & Config
  2. Data Loading
  3. Steady-State Revenue Model
  4. Single-Draw Optimisation
  5. Posterior Optimisation (main loop)
  6. Budget Response Curves
  7. Visualisation
  8. Results Table
  9. Entry Point

Run with:
    python budget_optimisation.py

Dependencies:
    outputs/idata_hierarchical.nc   ← saved by Phase 4
    outputs/roas_summary.csv        ← saved by Phase 5
    synthetic_raw.csv               ← raw spend data

Outputs (saved to outputs/):
    fig_optimal_allocation.png      ← current vs optimal spend per channel/region
    fig_budget_response_curves.png  ← optimal revenue across budget scenarios
    fig_allocation_uncertainty.png  ← posterior distribution of optimal allocations
    budget_recommendations.csv      ← full recommendation table
"""

