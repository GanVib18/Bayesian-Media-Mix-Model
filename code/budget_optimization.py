# 3. STEADY-STATE REVENUE MODEL
# ══════════════════════════════════════════════════════════════════════════════

def steady_state_adstock(spend: np.ndarray, alpha: float | np.ndarray) -> np.ndarray:
    """
    Steady-state geometric adstock for constant weekly spend s:

        adstock_ss = s / (1 - alpha)

    This is the fixed point of the adstock recursion when spend is constant.
    It gives a clean, differentiable approximation suitable for optimisation.

    Parameters
    ----------
    spend : np.ndarray, shape (C,) — weekly spend per channel
    alpha : scalar or (C,) — adstock decay rates

    Returns
    -------
    np.ndarray, shape (C,) — steady-state adstock
    """
    return spend / (1.0 - alpha + 1e-8)


def hill_saturation_np(x: np.ndarray, k: np.ndarray,
                        ec: np.ndarray) -> np.ndarray:
    """Vectorised Hill saturation over arrays."""
    safe_x = np.where(x <= 0, 1e-10, x)
    return safe_x**k / (safe_x**k + ec**k)


def predict_revenue(spend_vec: np.ndarray,
                    alpha_vec: np.ndarray,
                    k_vec:     np.ndarray,
                    ec_vec:    np.ndarray,
                    beta_vec:  np.ndarray,
                    p95_vec:   np.ndarray) -> float:
    """
    Predict total media revenue for a given spend allocation.

    This is the objective function the optimiser maximises. It does NOT
    include baseline revenue (which is unaffected by spend allocation),
    so we are maximising incremental media-driven revenue.

    Parameters
    ----------
    spend_vec : (C,) — proposed weekly spend per channel
    alpha_vec : (C,) — adstock decay rates
    k_vec     : (C,) — Hill slope parameters
    ec_vec    : (C,) — Hill half-saturation parameters
    beta_vec  : (C,) — channel revenue coefficients
    p95_vec   : (C,) — p95 normalisation constants

    Returns
    -------
    float — total predicted media revenue contribution
    """
    adstock_ss   = steady_state_adstock(spend_vec, alpha_vec)
    adstock_norm = adstock_ss / (p95_vec + 1e-8)
    saturation   = hill_saturation_np(adstock_norm, k_vec, ec_vec)
    return float(np.sum(beta_vec * saturation))


