def build_recommendation_table(opt_results: dict,
                                 save_path: str = "outputs/budget_recommendations.csv") -> pd.DataFrame:
    """
    Build and save the full budget recommendation table.

    Columns
    -------
    region, channel,
    current_spend_weekly,
    optimal_spend_mean, optimal_spend_lo90, optimal_spend_hi90,
    spend_delta_mean,               ← optimal - current
    spend_delta_pct,                ← % change from current
    revenue_uplift_mean_weekly,     ← additional weekly media revenue
    revenue_uplift_pct              ← % improvement over current allocation
    """
    rows = []

    print("\n  ── Budget Recommendation Table ──")
    print(f"  {'Region':<15} {'Channel':<12} {'Current':>10} "
          f"{'Optimal':>10} {'Change':>10} {'90% CI':>20}")
    print("  " + "─" * 80)

    for r, region in enumerate(REGIONS):
        res           = opt_results[region]
        current_spend = res["current_spend"]
        opt_draws     = res["optimal_spend"]
        uplift_draws  = res["pct_uplift"]

        opt_mean = opt_draws.mean(axis=0)
        opt_lo   = np.percentile(opt_draws,  5, axis=0)
        opt_hi   = np.percentile(opt_draws, 95, axis=0)

        mean_uplift_pct = float(uplift_draws.mean())
        mean_rev_uplift = float(res["revenue_uplift"].mean())

        for c, ch in enumerate(CHANNELS):
            delta      = opt_mean[c] - current_spend[c]
            delta_pct  = delta / current_spend[c] * 100

            rows.append({
                "region":                  region,
                "channel":                 ch,
                "current_spend_weekly":    round(current_spend[c],  0),
                "optimal_spend_mean":      round(opt_mean[c],       0),
                "optimal_spend_lo90":      round(opt_lo[c],         0),
                "optimal_spend_hi90":      round(opt_hi[c],         0),
                "spend_delta_mean":        round(delta,             0),
                "spend_delta_pct":         round(delta_pct,         1),
                "revenue_uplift_mean_wkly": round(mean_rev_uplift,  0),
                "revenue_uplift_pct":      round(mean_uplift_pct,   2),
            })

            sign = "+" if delta >= 0 else ""
            print(f"  {REGION_LABELS[region]:<15} {CHANNEL_LABELS[ch]:<12} "
                  f"${current_spend[c]/1e3:>7.1f}K  "
                  f"${opt_mean[c]/1e3:>7.1f}K  "
                  f"{sign}${delta/1e3:>6.1f}K  "
                  f"[${opt_lo[c]/1e3:.1f}K, ${opt_hi[c]/1e3:.1f}K]")

        print(f"  {'':15} {'Revenue uplift':12} "
              f"{'':10} {'':10}  "
              f"+${mean_rev_uplift/1e3:.1f}K/wk  ({mean_uplift_pct:+.1f}%)\n")

    df = pd.DataFrame(rows)
    df.to_csv(save_path, index=False)
    print(f"\n  ✓ Recommendations saved: {save_path}")
    return df


