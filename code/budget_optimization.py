def run_phase6(
    idata_path:    str   = "idata_hierarchical.nc",
    raw_data_path: str   = "synthetic_raw.csv",
    n_opt_draws:   int   = N_OPT_DRAWS,
    run_response_curves: bool = True,
):
    """
    Full Phase 6 pipeline:
        1. Load InferenceData, raw spend, compute current budgets and p95 constants
        2. Extract posterior samples for optimisation
        3. Run posterior optimisation at current budget level
        4. Run budget response curves across 50%–200% of current spend
        5. Plot optimal allocation (current vs. optimal, net reallocation)
        6. Plot budget response curves
        7. Plot allocation uncertainty (violin plots)
        8. Build and save recommendation table

    Parameters
    ----------
    idata_path         : Path to Phase 4 InferenceData.
    raw_data_path      : Path to synthetic_raw.csv.
    n_opt_draws        : Number of posterior draws to use (default 500).
                         Increase to 1000+ for final results; 200 for quick test.
    run_response_curves: If True, run budget response curves (adds ~50% runtime).
                         Set to False for a quick allocation-only run.

    Quick smoke-test
    ----------------
        run_phase6(n_opt_draws=50, run_response_curves=False)
    """
    global N_OPT_DRAWS
    N_OPT_DRAWS = n_opt_draws

    print("=" * 70)
    print("MapleThread Outdoor Co. — Phase 6: Budget Optimisation")
    print(f"{N_REGIONS} regions  ×  {len(CHANNELS)} channels  ×  {n_opt_draws} posterior draws")
    print("=" * 70)

    # ── Step 1: Load data ─────────────────────────────────────────────────────
    print("\n[1/6] Loading data...")
    idata   = load_idata(idata_path)
    raw_df  = load_raw_data(raw_data_path)
    budgets = compute_current_budgets(raw_df)
    p95     = compute_p95_constants(raw_df)

    print("\n  Current mean weekly budgets:")
    for region in REGIONS:
        total = sum(budgets[region].values())
        parts = "  |  ".join(
            f"{CHANNEL_LABELS[ch]}: ${budgets[region][ch]/1e3:.1f}K"
            for ch in CHANNELS
        )
        print(f"    {REGION_LABELS[region]:<15}: {parts}  →  Total: ${total/1e3:.1f}K")

    # ── Step 2: Extract posterior samples ─────────────────────────────────────
    print(f"\n[2/6] Extracting {n_opt_draws} posterior draws...")
    samples = extract_posterior_samples(idata, n_draws=n_opt_draws)

    # ── Step 3: Posterior optimisation at current budget ──────────────────────
    print(f"\n[3/6] Running posterior optimisation (current budget)...")
    print(f"  This runs {n_opt_draws} SciPy optimisations per region "
          f"({n_opt_draws * N_REGIONS:,} total). May take several minutes.\n")
    opt_results = run_posterior_optimisation(samples, p95, budgets,
                                              budget_multiplier=1.0)

    # ── Step 4: Budget response curves ────────────────────────────────────────
    response = None
    if run_response_curves:
        print(f"\n[4/6] Running budget response curves "
              f"({len(BUDGET_SCENARIOS)} scenarios × {n_opt_draws // 2} draws)...")
        response = run_budget_response_curves(samples, p95, budgets)
    else:
        print("\n[4/6] Skipping budget response curves (run_response_curves=False).")

    # ── Step 5: Plot optimal allocation ───────────────────────────────────────
    print("\n[5/6] Plotting results...")
    plot_optimal_allocation(opt_results)

    if response is not None:
        plot_budget_response_curves(response, budgets)

    plot_allocation_uncertainty(opt_results)

    # ── Step 6: Recommendation table ──────────────────────────────────────────
    print("\n[6/6] Building recommendation table...")
    rec_df = build_recommendation_table(opt_results)

    print("\n" + "=" * 70)
    print("Phase 6 complete. ✓")
    print("Outputs:")
    print("  outputs/fig_optimal_allocation.png")
    print("  outputs/fig_allocation_uncertainty.png")
    if response is not None:
        print("  outputs/fig_budget_response_curves.png")
    print("  outputs/budget_recommendations.csv")
    print("Next step → Phase 7: Writeup and Presentation")
    print("=" * 70)

    return opt_results, response, rec_df


