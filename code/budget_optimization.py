# 4. SINGLE-DRAW OPTIMISATION
# ══════════════════════════════════════════════════════════════════════════════

def optimise_single_draw(alpha_vec:    np.ndarray,
                          k_vec:        np.ndarray,
                          ec_vec:       np.ndarray,
                          beta_vec:     np.ndarray,
                          p95_vec:      np.ndarray,
                          current_spend: np.ndarray,
                          total_budget:  float,
                          spend_bounds:  list[tuple]) -> np.ndarray:
    """
    Solve the budget optimisation for a single posterior draw.

    Problem
    -------
    Maximise:   Σ_c beta_c × Hill(adstock_ss_c / p95_c ; k_c, ec_c)
    Subject to: Σ_c s_c = total_budget   (equality)
                lb_c ≤ s_c ≤ ub_c         (bounds per channel)

    Solver: SLSQP (Sequential Least Squares Programming) from SciPy.
    This handles both equality constraints and bounds natively and is
    well-suited to smooth nonlinear objectives of this form.

    Initialisation: proportional to current spend (feasible starting point).
    We also try a uniform initialisation and take the better result to reduce
    sensitivity to starting point.

    Parameters
    ----------
    spend_bounds : list of (lb, ub) per channel
        Lower bound: 10% of current spend (don't zero out any channel).
        Upper bound: 300% of current spend (prevent degenerate solutions).

    Returns
    -------
    np.ndarray, shape (C,) — optimal spend allocation for this draw
    """
    def neg_revenue(s):
        return -predict_revenue(s, alpha_vec, k_vec, ec_vec, beta_vec, p95_vec)

    constraints = [{"type": "eq", "fun": lambda s: s.sum() - total_budget}]

    # Initialisation 1: proportional to current spend (always feasible)
    x0_prop = current_spend * (total_budget / current_spend.sum())

    # Initialisation 2: uniform allocation
    x0_unif = np.full(N_CHANNELS, total_budget / N_CHANNELS)
    # Clip to bounds
    x0_unif = np.clip(x0_unif,
                       [b[0] for b in spend_bounds],
                       [b[1] for b in spend_bounds])
    x0_unif = x0_unif * (total_budget / x0_unif.sum())

    best_result = None
    best_val    = np.inf

    for x0 in [x0_prop, x0_unif]:
        result = minimize(
            neg_revenue,
            x0,
            method="SLSQP",
            bounds=spend_bounds,
            constraints=constraints,
            options={"ftol": 1e-9, "maxiter": 500, "disp": False},
        )
        if result.success and result.fun < best_val:
            best_val    = result.fun
            best_result = result

    if best_result is None or not best_result.success:
        # Fallback: return proportional allocation if optimiser fails
        return x0_prop

    return best_result.x


