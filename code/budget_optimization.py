# 7. VISUALISATION
# ══════════════════════════════════════════════════════════════════════════════

def plot_optimal_allocation(opt_results: dict,
                             save_path: str = "outputs/fig_optimal_allocation.png"):
    """
    Current vs. optimal spend per channel per region.

    Two panel types per region:
      Left:  Grouped bar chart — current spend (grey) vs posterior mean optimal (coloured).
             Error bars on optimal bars show 90% credible interval.
      Right: Net reallocation arrows — how much budget shifts from/to each channel.

    This is the primary business recommendation output.
    """
    print("\n  Plotting optimal allocation...")

    fig, axes = plt.subplots(N_REGIONS, 2, figsize=(14, 4.5 * N_REGIONS))
    fig.suptitle(
        "MapleThread — Current vs. Optimal Budget Allocation\n"
        "Grey = current spend  |  Coloured = posterior mean optimal  |  "
        "Error bar = 90% credible interval",
        fontsize=13, fontweight="bold", y=1.005,
    )

    for r, region in enumerate(REGIONS):
        res           = opt_results[region]
        current_spend = res["current_spend"]          # (C,)
        opt_draws     = res["optimal_spend"]           # (n_draws, C)

        opt_mean = opt_draws.mean(axis=0)
        opt_lo   = np.percentile(opt_draws,  5, axis=0)
        opt_hi   = np.percentile(opt_draws, 95, axis=0)

        x_pos = np.arange(N_CHANNELS)
        width = 0.35

        # ── Left: grouped bars ────────────────────────────────────────────────
        ax = axes[r, 0]
        ax.bar(x_pos - width / 2, current_spend / 1e3, width,
               color=PALETTE["current"], alpha=0.75, label="Current", zorder=3)
        ax.bar(x_pos + width / 2, opt_mean / 1e3, width,
               color=[PALETTE[ch] for ch in CHANNELS], alpha=0.82,
               label="Optimal (mean)", zorder=3)
        yerr_lo = np.clip((opt_mean - opt_lo) / 1e3, 0, None)
        yerr_hi = np.clip((opt_hi - opt_mean) / 1e3, 0, None)
        ax.errorbar(
            x_pos + width / 2, opt_mean / 1e3,
            yerr=[yerr_lo, yerr_hi],
            fmt="none", color="black", capsize=4, elinewidth=1.5,
            capthick=1.5, zorder=4,
        )

        ax.set_xticks(x_pos)
        ax.set_xticklabels([CHANNEL_LABELS[ch] for ch in CHANNELS],
                            fontsize=9, rotation=15, ha="right")
        ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x:.0f}K"))
        ax.set_ylabel("Weekly Spend ($K)", fontsize=9)
        ax.set_title(f"{REGION_LABELS[region]} — Spend Allocation",
                     fontsize=10, fontweight="bold", color=PALETTE[region])
        ax.legend(fontsize=8, loc="upper right")

        # ── Right: net reallocation ───────────────────────────────────────────
        ax2 = axes[r, 1]
        delta = (opt_mean - current_spend) / 1e3

        colors = [PALETTE[ch] if d >= 0 else PALETTE["current"]
                  for ch, d in zip(CHANNELS, delta)]
        bars = ax2.barh(np.arange(N_CHANNELS), delta, color=colors,
                        alpha=0.82, height=0.5, zorder=3)
        ax2.axvline(0, color="black", lw=1.2, alpha=0.7)

        for i, (d, lo, hi, ch) in enumerate(zip(
            delta,
            (opt_lo - current_spend) / 1e3,
            (opt_hi - current_spend) / 1e3,
            CHANNELS,
        )):
            xerr_lo = max(d - lo, 0)
            xerr_hi = max(hi - d, 0)
            ax2.errorbar(d, i,
                         xerr=[[xerr_lo], [xerr_hi]],
                         fmt="none", color="black",
                         capsize=4, elinewidth=1.5, capthick=1.5, zorder=4)
            sign = "+" if d >= 0 else ""
            ax2.text(d + (0.3 if d >= 0 else -0.3), i,
                     f"{sign}${d:.1f}K", va="center",
                     ha="left" if d >= 0 else "right",
                     fontsize=8, fontweight="bold", color=PALETTE[ch])

        ax2.set_yticks(np.arange(N_CHANNELS))
        ax2.set_yticklabels([CHANNEL_LABELS[ch] for ch in CHANNELS], fontsize=9)
        ax2.xaxis.set_major_formatter(
            mticker.FuncFormatter(lambda x, _: f"${x:+.0f}K"))
        ax2.set_xlabel("Weekly Spend Change ($K)", fontsize=9)
        ax2.set_title(f"{REGION_LABELS[region]} — Net Reallocation",
                      fontsize=10, fontweight="bold", color=PALETTE[region])

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Optimal allocation plot saved: {save_path}")


def plot_budget_response_curves(response: dict,
                                 current_budgets: dict,
                                 save_path: str = "outputs/fig_budget_response_curves.png"):
    """
    Optimal media revenue vs. total budget level for each region.

    The x-axis shows total budget as a multiple of current spend.
    The y-axis shows optimal media revenue contribution (not total revenue —
    baseline is excluded as it is budget-independent).

    The curve shape reveals:
      - Steep slope at low budgets = high marginal returns (underinvested)
      - Flattening at high budgets = diminishing returns at scale
      - The "elbow" = approximate efficient frontier point

    Shaded band = 90% credible interval across posterior draws.
    """
    print("\n  Plotting budget response curves...")

    fig, axes = plt.subplots(2, 3, figsize=(18, 10))
    axes_flat = axes.flatten()
    fig.suptitle(
        "MapleThread — Budget Response Curves\n"
        "Optimal media revenue at each total budget level  |  "
        "Shaded = 90% credible interval  |  ★ = current budget",
        fontsize=13, fontweight="bold",
    )

    for r, region in enumerate(REGIONS):
        ax    = axes_flat[r]
        color = PALETTE[region]

        current_total = sum(current_budgets[region].values())
        budgets       = [response[region][m]["total_budget"] for m in BUDGET_SCENARIOS]
        means         = [response[region][m]["mean_rev"] for m in BUDGET_SCENARIOS]
        lo90s         = [response[region][m]["lo90_rev"] for m in BUDGET_SCENARIOS]
        hi90s         = [response[region][m]["hi90_rev"] for m in BUDGET_SCENARIOS]

        budgets_k = [b / 1e3 for b in budgets]
        means_k   = [m / 1e3 for m in means]
        lo90s_k   = [l / 1e3 for l in lo90s]
        hi90s_k   = [h / 1e3 for h in hi90s]

        ax.fill_between(budgets_k, lo90s_k, hi90s_k, alpha=0.2, color=color)
        ax.plot(budgets_k, means_k, color=color, lw=2.5, marker="o",
                markersize=6, label="Mean optimal revenue")

        # Current budget marker
        current_idx = BUDGET_SCENARIOS.index(1.0)
        ax.scatter([budgets_k[current_idx]], [means_k[current_idx]],
                   color=color, s=200, marker="*", zorder=5,
                   label="Current budget", edgecolors="black", linewidths=0.8)

        ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x:.0f}K"))
        ax.xaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x:.0f}K"))
        ax.set_xlabel("Total Weekly Budget ($K)", fontsize=9)
        ax.set_ylabel("Optimal Media Revenue ($K)", fontsize=9)
        ax.set_title(REGION_LABELS[region], fontsize=11,
                     fontweight="bold", color=color)
        ax.legend(fontsize=8, loc="lower right")

    # Hide unused subplot (6th panel for 5 regions)
    axes_flat[-1].set_visible(False)

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Budget response curves saved: {save_path}")


def plot_allocation_uncertainty(opt_results: dict,
                                 save_path: str = "outputs/fig_allocation_uncertainty.png"):
    """
    Posterior distribution of optimal spend per channel per region.

    Violin plots showing the full posterior distribution of optimal spend
    for each channel, giving an honest picture of how much uncertainty
    exists in the recommendation.

    Wide violins = high parameter uncertainty → recommendation should be
    treated as directional, not prescriptive.
    Narrow violins = strong posterior agreement → high confidence in number.
    """
    print("\n  Plotting allocation uncertainty...")

    fig, axes = plt.subplots(1, N_REGIONS, figsize=(4.5 * N_REGIONS, 6),
                              sharey=False)
    fig.suptitle(
        "MapleThread — Posterior Distribution of Optimal Spend per Channel\n"
        "Width of violin = uncertainty in recommendation  |  "
        "White dot = posterior mean  |  Bar = 90% CI",
        fontsize=12, fontweight="bold",
    )

    for r, region in enumerate(REGIONS):
        ax        = axes[r]
        res       = opt_results[region]
        opt_draws = res["optimal_spend"]     # (n_draws, C)
        curr      = res["current_spend"]     # (C,)

        data_list = [opt_draws[:, c] / 1e3 for c in range(N_CHANNELS)]

        parts = ax.violinplot(
            data_list,
            positions=np.arange(N_CHANNELS),
            showmeans=False, showmedians=False, showextrema=False,
        )
        for i, pc in enumerate(parts["bodies"]):
            pc.set_facecolor(PALETTE[CHANNELS[i]])
            pc.set_alpha(0.65)

        # Mean and 90% CI markers
        for c in range(N_CHANNELS):
            mean_val = float(opt_draws[:, c].mean()) / 1e3
            lo_val   = float(np.percentile(opt_draws[:, c],  5)) / 1e3
            hi_val   = float(np.percentile(opt_draws[:, c], 95)) / 1e3
            ax.scatter([c], [mean_val], color="white", s=40, zorder=5)
            ax.vlines(c, lo_val, hi_val, color="black", lw=2, zorder=4)

        # Current spend as horizontal ticks
        for c in range(N_CHANNELS):
            ax.scatter([c], [curr[c] / 1e3], marker="_", color="black",
                       s=200, linewidths=2.5, zorder=5,
                       label="Current spend" if c == 0 else "")

        ax.set_xticks(np.arange(N_CHANNELS))
        ax.set_xticklabels([CHANNEL_LABELS[ch] for ch in CHANNELS],
                            fontsize=8, rotation=20, ha="right")
        ax.yaxis.set_major_formatter(
            mticker.FuncFormatter(lambda x, _: f"${x:.0f}K"))
        ax.set_ylabel("Weekly Spend ($K)" if r == 0 else "", fontsize=9)
        ax.set_title(REGION_LABELS[region], fontsize=10,
                     fontweight="bold", color=PALETTE[region])
        if r == 0:
            ax.legend(fontsize=8, loc="upper right")

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Allocation uncertainty plot saved: {save_path}")


