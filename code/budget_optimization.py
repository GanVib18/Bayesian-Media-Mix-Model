# 6. BUDGET RESPONSE CURVES
# ══════════════════════════════════════════════════════════════════════════════

def run_budget_response_curves(samples:        dict,
                                p95_constants:  dict,
                                current_budgets: dict) -> dict:
    """
    Run optimisation across a range of total budget levels per region.

    For each budget scenario (50%–200% of current) and each posterior draw,
    we find the optimal allocation and record the resulting revenue.

    This answers: "What happens to optimal revenue as we increase or decrease
    the total marketing budget?" — the primary strategic planning question.

    We use a subset of draws (N_OPT_DRAWS // 2) per scenario to keep
    runtime manageable while preserving uncertainty estimates.

    Returns
    -------
    dict: region → {scenario_multiplier: {"mean_rev", "lo90_rev", "hi90_rev"}}
    """
    ch_param_keys = {
        "tv":          ("alpha_tv",   "k_tv",   "ec_tv",   "beta_tv"),
        "paid_search": ("alpha_ps",   "k_ps",   "ec_ps",   "beta_ps"),
        "social":      ("alpha_so",   "k_so",   "ec_so",   "beta_so"),
        "display":     ("alpha_disp", "k_disp", "ec_disp", "beta_disp"),
    }

    # Use half the draws per scenario — sufficient for smooth curves
    n_draws_rc = max(100, N_OPT_DRAWS // 2)
    n_draws    = next(iter(samples.values())).shape[0]
    rng        = np.random.default_rng(RANDOM_SEED + 1)
    draw_idx   = rng.choice(n_draws, size=min(n_draws_rc, n_draws), replace=False)

    response = {}

    for r, region in enumerate(REGIONS):
        response[region] = {}
        current_spend = np.array([
            current_budgets[region][ch] for ch in CHANNELS
        ])
        p95_vec = np.array([p95_constants[ch][r] for ch in CHANNELS])

        for mult in BUDGET_SCENARIOS:
            total_budget = float(current_spend.sum() * mult)
            spend_bounds = [
                (max(0.10 * current_spend[c], 1.0),
                 min(3.00 * current_spend[c], total_budget * 0.9))
                for c in range(N_CHANNELS)
            ]

            rev_draws = np.zeros(len(draw_idx))

            for i, d in enumerate(draw_idx):
                alpha_vec = np.array([float(samples[ch_param_keys[ch][0]][d, r]) for ch in CHANNELS])
                k_vec     = np.array([float(samples[ch_param_keys[ch][1]][d, r]) for ch in CHANNELS])
                ec_vec    = np.array([float(samples[ch_param_keys[ch][2]][d, r]) for ch in CHANNELS])
                beta_vec  = np.array([float(samples[ch_param_keys[ch][3]][d, r]) for ch in CHANNELS])

                opt_spend = optimise_single_draw(
                    alpha_vec, k_vec, ec_vec, beta_vec, p95_vec,
                    current_spend, total_budget, spend_bounds,
                )
                rev_draws[i] = predict_revenue(
                    opt_spend, alpha_vec, k_vec, ec_vec, beta_vec, p95_vec
                )

            response[region][mult] = {
                "mean_rev": float(rev_draws.mean()),
                "lo90_rev": float(np.percentile(rev_draws,  5)),
                "hi90_rev": float(np.percentile(rev_draws, 95)),
                "total_budget": total_budget,
            }

        print(f"    {REGION_LABELS[region]:>15s}: response curves complete.")

    return response


