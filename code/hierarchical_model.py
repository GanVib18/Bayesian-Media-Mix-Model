# 4. PYTENSOR MEDIA TRANSFORMS (vectorised, no scan)
# ══════════════════════════════════════════════════════════════════════════════

def pytensor_geometric_adstock_vec(lag_matrix: pt.TensorVariable,
                                    lags: np.ndarray,
                                    alpha: pt.TensorVariable) -> pt.TensorVariable:
    """
    Vectorised geometric adstock via lag-matrix dot product — no scan required.

    adstock[t] = Σ_{l=0}^{L-1} alpha^l × spend[t-l]
               = lag_matrix[t] · weight_vector

    Parameters
    ----------
    lag_matrix : (T, MAX_LAG) — fixed data constant
    lags       : (MAX_LAG,)  — integer lag indices
    alpha      : scalar symbolic decay rate in [0, 1)

    Returns
    -------
    pt.TensorVariable of shape (T,)
    """
    weights = alpha ** pt.as_tensor_variable(lags)
    return pt.dot(lag_matrix, weights)


def pytensor_hill(x: pt.TensorVariable,
                  k: pt.TensorVariable,
                  ec: pt.TensorVariable) -> pt.TensorVariable:
    """
    Hill saturation: S(x) = x^k / (x^k + ec^k)

    Numerically safe: replaces x=0 with a small epsilon so gradients are
    well-defined. The result is effectively 0 at x ≈ 0.
    """
    safe_x = pt.switch(pt.eq(x, 0.0), 1e-10, x)
    return safe_x**k / (safe_x**k + ec**k)


