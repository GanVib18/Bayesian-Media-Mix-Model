    """
    Plot posterior distributions against true DGP values for all regions.

    Layout: one column per region, one row per parameter group (alpha, k, ec, beta).
    The true DGP adstock/Hill parameters are shared across regions — individual
    region posteriors should all be near the same true value.
    Betas differ per region — each panel shows that region's true value.

    Expected pattern
    ----------------
    - Large markets (Canada, US): narrower posteriors, closer to true value.
    - Small market (Australia): wider posteriors, more shrinkage toward population mean.
    - This differential posterior width IS the partial pooling working correctly.
    """
