# 9. POOLING SHRINKAGE VISUALISATION
# ══════════════════════════════════════════════════════════════════════════════

def plot_pooling_shrinkage(idata: az.InferenceData,
                            raw_df: pd.DataFrame,
                            save_path: str = "outputs/fig_pooling_shrinkage.png"):
    """
    Visualise the partial pooling (shrinkage) effect for channel betas and alpha_tv.

    For each parameter, we plot:
      - The per-region posterior mean (coloured dot)
      - The per-region 94% HDI (horizontal error bar)
      - The population posterior mean (vertical dashed line)

    The expected pattern: regions with less data (Australia) have wider credible
    intervals AND their posterior mean is pulled closer to the population mean
    than data-rich regions (Canada, United States). This is partial pooling.

    We also show a separate panel comparing per-region data volume (total spend
    weeks × channels) as a proxy for information content.
    """
    print("\n  Plotting pooling shrinkage...")

    posterior = idata.posterior

    # Parameters to visualise (per-region arrays) + their population mean
    shrinkage_params = [
        ("beta_tv",   "mu_log_beta_tv",   "β TV ($)",          True,  PALETTE["tv"]),
        ("beta_ps",   "mu_log_beta_ps",   "β Paid Search ($)",  True,  PALETTE["paid_search"]),
        ("beta_so",   "mu_log_beta_so",   "β Social ($)",       True,  PALETTE["social"]),
        ("beta_disp", "mu_log_beta_disp", "β Display ($)",      True,  PALETTE["display"]),
        ("alpha_tv",  "mu_alpha_tv",      "α TV",               False, PALETTE["tv"]),
        ("alpha_ps",  "mu_alpha_ps",      "α Paid Search",      False, PALETTE["paid_search"]),
    ]

    n_rows = len(shrinkage_params)
    fig, axes = plt.subplots(n_rows, 1, figsize=(12, 3.5 * n_rows))
    fig.suptitle(
        "Partial Pooling (Shrinkage) — Per-Region vs Population Mean\n"
        "Smaller markets should be pulled toward the population mean\n"
        "Error bars = 94% HDI  |  Dashed line = population posterior mean",
        fontsize=12, fontweight="bold", y=1.01,
    )

    for ax, (param, pop_param, label, is_lognormal, color) in zip(axes, shrinkage_params):

        region_means = []
        region_lo    = []
        region_hi    = []

        for r, region in enumerate(REGIONS):
            samples_r = posterior[param].values[:, :, r].flatten()
            region_means.append(float(samples_r.mean()))
            hdi_r = az.hdi(samples_r, hdi_prob=0.94)
            region_lo.append(float(hdi_r[0]))
            region_hi.append(float(hdi_r[1]))

        # Population mean (for log-normal params, exp of the log-mean)
        pop_samples = posterior[pop_param].values.flatten()
        if is_lognormal:
            pop_mean = float(np.exp(pop_samples.mean()))
        else:
            pop_mean = float(pop_samples.mean())

        # True values per region (for beta; shared for alpha)
        true_vals = []
        for region in REGIONS:
            if "beta" in param:
                ch = param.replace("beta_", "").replace("ps", "paid_search").replace(
                    "so", "social").replace("disp", "display")
                true_vals.append(TRUE_PARAMS["beta"][region][ch])
            else:
                ch = param.replace("alpha_", "").replace("ps", "paid_search").replace(
                    "so", "social").replace("disp", "display")
