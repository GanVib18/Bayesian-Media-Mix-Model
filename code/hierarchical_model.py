def run_phase4(
    sampling_draws:  int   = 1000,
    sampling_tune:   int   = 1000,
    sampling_chains: int   = 4,
    target_accept:   float = 0.92,
    prior_samples:   int   = 300,
    save_idata:      bool  = True,
):
    """
    Full Phase 4 pipeline:
        1. Load all-region data
        2. Build hierarchical model inputs
        3. Build hierarchical PyMC model
        4. Prior predictive check
        5. MCMC sampling
        6. Diagnostics
        7. Parameter recovery (all regions)
        8. Pooling shrinkage visualisation
        9. Posterior contribution decomposition

    Parameters
    ----------
    sampling_draws  : Posterior draws per chain.
    sampling_tune   : Warmup steps per chain (more than Phase 3 due to model complexity).
    sampling_chains : Number of independent MCMC chains.
    target_accept   : NUTS target acceptance rate (higher than Phase 3).
    prior_samples   : Prior predictive samples per region.
    save_idata      : If True, save InferenceData to outputs/idata_hierarchical.nc.

    Quick smoke-test
    ----------------
    To validate the pipeline before a full run:
        run_phase4(sampling_draws=200, sampling_tune=200, sampling_chains=2)
    """
    print("=" * 70)
    print("MapleThread Outdoor Co. — Phase 4: Hierarchical Bayesian MMM")
    print(f"{N_REGIONS} regions  ×  {N_WEEKS} weeks  ×  {len(CHANNELS)} channels")
    print("=" * 70)

    # ── Step 1: Load data ─────────────────────────────────────────────────────
    print("\n[1/8] Loading data...")
    raw_df, gt_df = load_all_data()

    # ── Step 2: Build model inputs ────────────────────────────────────────────
    print("\n[2/8] Building hierarchical model inputs...")
    inputs = build_hierarchical_inputs(raw_df)
    print(f"  Revenue array shape:     {inputs['revenue'].shape}")
    print(f"  Lag matrix shape (TV):   {inputs['lag_matrices']['tv'].shape}")
    for ch in CHANNELS:
        p95s = inputs["p95"][ch]
        print(f"  p95 ({ch:>12s}): " +
              " | ".join(f"{r[:3].upper()} ${v:>8,.0f}" for r, v in
                          zip(REGIONS, p95s)))

    # ── Step 3: Build model ───────────────────────────────────────────────────
    print("\n[3/8] Building hierarchical PyMC model...")
    model = build_hierarchical_model(inputs)
    print(f"  Free parameters:  {len(model.free_RVs)}")
    print(f"  (Phase 3 Canada had ~20 free params; expect ~120+ here)")

    # ── Step 4: Prior predictive check ────────────────────────────────────────
    print("\n[4/8] Prior predictive check...")
    prior_pred = run_prior_predictive(model, inputs, n_samples=prior_samples)

    # ── Step 5: MCMC sampling ─────────────────────────────────────────────────
    print("\n[5/8] MCMC sampling...")
    idata = run_sampling(
        model,
        draws=sampling_draws,
        tune=sampling_tune,
        chains=sampling_chains,
        target_accept=target_accept,
    )

    # ── Step 6: Diagnostics ───────────────────────────────────────────────────
    print("\n[6/8] Diagnostics...")
    summary = run_diagnostics(idata)

    # ── Step 7: Parameter recovery ────────────────────────────────────────────
    print("\n[7/8] Parameter recovery...")
    plot_parameter_recovery(idata)

    # ── Step 8: Pooling shrinkage ─────────────────────────────────────────────
    print("\n[8/8] Pooling shrinkage + posterior contributions...")
    plot_pooling_shrinkage(idata, raw_df)
    plot_posterior_contributions(idata, inputs)

    # ── Save InferenceData ────────────────────────────────────────────────────
    if save_idata:
        idata_path = "outputs/idata_hierarchical.nc"
        idata.to_netcdf(idata_path)
        print(f"\n  ✓ InferenceData saved: {idata_path}")

    print("\n" + "=" * 70)
    print("Phase 4 complete. ✓")
    print("Next step → Phase 5: Posterior Analysis and Channel Attribution")
    print("=" * 70)

    return model, idata, inputs


