# 7. MCMC SAMPLING & DIAGNOSTICS
# ══════════════════════════════════════════════════════════════════════════════

def run_sampling(model: pm.Model,
                 draws: int = 1000,
                 tune: int = 1000,
                 chains: int = 4,
                 target_accept: float = 0.92) -> az.InferenceData:
    """
    Sample the posterior with NUTS.

    Sampler settings
    ----------------
    tune=1000         : Generous warmup. Hierarchical models need more tuning
                        steps than single-region models because the hyperprior
                        geometry requires careful mass-matrix adaptation.
    target_accept=0.92: Slightly higher than Phase 3 (0.90) to handle the
                        more complex posterior geometry of the hierarchical model.
                        If divergences appear, increase to 0.95.
    chains=4          : 4 independent chains allow reliable R-hat computation
                        and chain-level stationarity checks.
    """
    print(f"\n  Sampling posterior (chains={chains}, draws={draws}, tune={tune})...")
    print(f"  Hierarchical models are slower than single-region.")
    print(f"  Expect ~5–15 minutes depending on your hardware.\n")

    with model:
        idata = pm.sample(
            draws=draws,
            tune=tune,
            chains=chains,
            target_accept=target_accept,
            random_seed=RANDOM_SEED,
            progressbar=True,
            nuts_sampler="numpyro",
            idata_kwargs={"log_likelihood": True},
        )

    return idata


def run_diagnostics(idata: az.InferenceData,
                    save_path: str = "outputs/fig_trace_hier.png"):
    """
    Run ArviZ diagnostics and save trace plots for key population-level parameters.

    Convergence criteria
    --------------------
    R-hat < 1.01  : Strong convergence (< 1.05 acceptable minimum).
    ESS > 400     : Enough effective samples for reliable inference.
    Divergences   : Any divergences indicate model geometry problems.
                    Common fixes: increase target_accept, tighten σ hyperpriors,
                    or switch alpha/ec to full logit-normal parameterisation.
    """
    print("\n  Running diagnostics...")

    # ── R-hat / ESS summary on population-level parameters ───────────────────
    pop_vars = [
        "mu_alpha_tv", "mu_alpha_ps", "mu_alpha_so", "mu_alpha_disp",
        "sigma_alpha_tv", "sigma_alpha_ps",
        "mu_log_k_tv", "mu_log_k_ps", "mu_log_k_so", "mu_log_k_disp",
        "mu_ec_tv", "mu_ec_ps", "mu_ec_so", "mu_ec_disp",
        "mu_log_beta_tv", "mu_log_beta_ps", "mu_log_beta_so", "mu_log_beta_disp",
        "mu_log_intercept", "mu_log_trend",
    ]

    # Per-region parameter arrays (shape R per param)
    region_vars = [
        "alpha_tv", "alpha_ps", "alpha_so", "alpha_disp",
        "k_tv", "k_ps", "k_so", "k_disp",
        "ec_tv", "ec_ps", "ec_so", "ec_disp",
        "beta_tv", "beta_ps", "beta_so", "beta_disp",
        "intercept", "trend_slope",
    ]

    all_diag_vars = pop_vars + region_vars
    summary = az.summary(idata, var_names=all_diag_vars, round_to=4)

    print("\n  ── Population-Level Posterior Summary ──")
    pop_summary = az.summary(idata, var_names=pop_vars, round_to=4)
    print(pop_summary[["mean", "sd", "hdi_3%", "hdi_97%", "r_hat", "ess_bulk"]].to_string())

    n_divergences = int(idata.sample_stats["diverging"].values.sum())
    print(f"\n  Divergences: {n_divergences}")
    if n_divergences > 0:
        print("  ⚠ Divergences detected.")
        print("    → Try: higher target_accept (0.95+), tighter sigma hyperpriors,")
        print("           or logit-normal parameterisation for alpha/ec.")
    else:
        print("  ✓ No divergences.")

    max_rhat = summary["r_hat"].dropna().max()
    n_bad    = (summary["r_hat"].dropna() > 1.01).sum()
    min_ess  = summary["ess_bulk"].min()
    print(f"\n  Max R-hat across all params: {max_rhat:.4f}  (target: < 1.01)")
    print(f"  Parameters with R-hat > 1.01: {n_bad}")
    print(f"  Min bulk ESS: {min_ess:.0f}  (target: > 400)")

    # ── Trace plots — population-level only (per-region arrays too large) ─────
    trace_vars = [
        "mu_alpha_tv", "mu_alpha_ps",
        "mu_log_k_tv", "mu_log_k_ps",
        "mu_ec_tv", "mu_ec_ps",
        "mu_log_beta_tv", "mu_log_beta_ps",
        "mu_log_intercept", "mu_log_trend",
    ]

    axes = az.plot_trace(
        idata,
        var_names=trace_vars,
        figsize=(14, 22),
        compact=True,
    )
    fig = axes.ravel()[0].get_figure()
    fig.suptitle(
        "MCMC Trace Plots — Population-Level Hyperparameters\n"
        "Left: posterior density  |  Right: sample trace (should look like 'fuzzy caterpillar')",
        fontsize=11, fontweight="bold", y=1.005,
    )
    plt.tight_layout()
    plt.savefig(save_path, dpi=120, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Trace plot saved: {save_path}")

    return summary


