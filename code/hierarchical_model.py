# 5. MODEL DEFINITION
# ══════════════════════════════════════════════════════════════════════════════

def build_hierarchical_model(inputs: dict) -> pm.Model:
    """
    Build the hierarchical Bayesian MMM for all 5 regions.

    Parameterisation
    ----------------
    All per-region parameters use the non-centered parameterisation:

        param[r] = μ_param + σ_param × z_param[r]
        z_param[r] ~ Normal(0, 1)

    This improves NUTS geometry by decoupling the population-level parameters
    from the per-region offsets, reducing funnel-shaped posteriors.

    For parameters constrained to (0, 1) — alpha, ec — the raw non-centered
    value is clipped after shifting. An alternative is to work in logit space,
    but clipping is simpler and adequate when σ_param is small.

    For parameters constrained to (0, ∞) — k, beta — we use a log-normal
    non-centered parameterisation:
        log_param[r] = μ_log_param + σ_log_param × z_param[r]
        param[r]     = exp(log_param[r])

    Baseline parameters (intercept, trend_slope) also get partial pooling
    across regions, which is particularly valuable for Australia (smallest
    market, shortest effective data series).

    Baseline structure (per region)
    --------------------------------
    Baseline[r, t] = intercept[r]
                   + trend_slope[r] × t_std[t]
                   + fourier[t] · fourier_coefs[r, :]
                   + holiday_matrix[t] · holiday_deltas[r, :]
    """
    R              = inputs["R"]
    T              = inputs["T"]
    lags           = inputs["lags"]
    t_std          = pt.as_tensor_variable(inputs["t_std"].astype("float64"))
    fourier        = pt.as_tensor_variable(inputs["fourier"].astype("float64"))
    holiday_matrix = pt.as_tensor_variable(inputs["holiday_matrix"].astype("float64"))
    revenue_obs    = inputs["revenue"].astype("float64")   # (R, T)

    with pm.Model() as model:

        # ════════════════════════════════════════════════════════════════════
        # HYPERPRIORS — population-level distributions
        # ════════════════════════════════════════════════════════════════════

        # ── Adstock decay rates ───────────────────────────────────────────────
        # Population mean: channel-informed (same as Phase 3 per-channel priors).
        # Population spread σ ~ HalfNormal(0.15): most of the mass puts
        # cross-region variation within ±0.3 of the mean — regions share the
        # same channel type, so extreme divergence is not expected.

        mu_alpha_tv    = pm.Beta("mu_alpha_tv",   alpha=8,  beta=3)    # mean≈0.73
        mu_alpha_ps    = pm.Beta("mu_alpha_ps",   alpha=2,  beta=8)    # mean≈0.20
        mu_alpha_so    = pm.Beta("mu_alpha_so",   alpha=5,  beta=6)    # mean≈0.45
        mu_alpha_disp  = pm.Beta("mu_alpha_disp", alpha=2,  beta=10)   # mean≈0.17

        sigma_alpha_tv   = pm.HalfNormal("sigma_alpha_tv",   sigma=0.15)
        sigma_alpha_ps   = pm.HalfNormal("sigma_alpha_ps",   sigma=0.10)
        sigma_alpha_so   = pm.HalfNormal("sigma_alpha_so",   sigma=0.12)
        sigma_alpha_disp = pm.HalfNormal("sigma_alpha_disp", sigma=0.08)

        # ── Hill slope k ───────────────────────────────────────────────────────
        # Log-normal NCP: log(k) ~ Normal(μ_log_k, σ_log_k)
        # Priors on μ_log_k centred at log(true_k) for each channel.

        mu_log_k_tv   = pm.Normal("mu_log_k_tv",   mu=np.log(2.5), sigma=0.5)
        mu_log_k_ps   = pm.Normal("mu_log_k_ps",   mu=np.log(1.5), sigma=0.5)
        mu_log_k_so   = pm.Normal("mu_log_k_so",   mu=np.log(1.2), sigma=0.5)
        mu_log_k_disp = pm.Normal("mu_log_k_disp", mu=np.log(3.0), sigma=0.5)

        sigma_log_k_tv   = pm.HalfNormal("sigma_log_k_tv",   sigma=0.3)
        sigma_log_k_ps   = pm.HalfNormal("sigma_log_k_ps",   sigma=0.3)
        sigma_log_k_so   = pm.HalfNormal("sigma_log_k_so",   sigma=0.3)
        sigma_log_k_disp = pm.HalfNormal("sigma_log_k_disp", sigma=0.3)

        # ── Hill half-saturation ec ────────────────────────────────────────────
        # ec lives in (0, 1). Same NCP structure as alpha.

        mu_ec_tv   = pm.Beta("mu_ec_tv",   alpha=4, beta=6)    # mean≈0.40
        mu_ec_ps   = pm.Beta("mu_ec_ps",   alpha=6, beta=4)    # mean≈0.60
        mu_ec_so   = pm.Beta("mu_ec_so",   alpha=7, beta=3)    # mean≈0.70
        mu_ec_disp = pm.Beta("mu_ec_disp", alpha=3, beta=7)    # mean≈0.30

        sigma_ec_tv   = pm.HalfNormal("sigma_ec_tv",   sigma=0.10)
        sigma_ec_ps   = pm.HalfNormal("sigma_ec_ps",   sigma=0.10)
        sigma_ec_so   = pm.HalfNormal("sigma_ec_so",   sigma=0.10)
        sigma_ec_disp = pm.HalfNormal("sigma_ec_disp", sigma=0.10)

        # ── Channel coefficients β ─────────────────────────────────────────────
        # Log-normal NCP. Population means anchored near the largest market (Canada).
        # σ_log_beta ~ HalfNormal(0.5) allows ~2× variation across regions, which
        # matches the DGP (Canada beta ≈ 3.4× Australia beta for TV).

        mu_log_beta_tv   = pm.Normal("mu_log_beta_tv",   mu=np.log(200_000), sigma=0.8)
        mu_log_beta_ps   = pm.Normal("mu_log_beta_ps",   mu=np.log(160_000), sigma=0.8)
        mu_log_beta_so   = pm.Normal("mu_log_beta_so",   mu=np.log(120_000), sigma=0.8)
        mu_log_beta_disp = pm.Normal("mu_log_beta_disp", mu=np.log( 48_000), sigma=0.8)

        sigma_log_beta_tv   = pm.HalfNormal("sigma_log_beta_tv",   sigma=0.6)
        sigma_log_beta_ps   = pm.HalfNormal("sigma_log_beta_ps",   sigma=0.6)
        sigma_log_beta_so   = pm.HalfNormal("sigma_log_beta_so",   sigma=0.6)
        sigma_log_beta_disp = pm.HalfNormal("sigma_log_beta_disp", sigma=0.6)

        # ── Baseline: intercept ────────────────────────────────────────────────
        # Log-normal NCP. Population mean near log($200K) — a diffuse centre
        # between Australia ($55K) and Canada ($620K).

        mu_log_intercept    = pm.Normal("mu_log_intercept",    mu=np.log(250_000), sigma=1.0)
        sigma_log_intercept = pm.HalfNormal("sigma_log_intercept", sigma=0.8)

        # ── Baseline: trend slope ─────────────────────────────────────────────
        # Log-normal NCP. Positive slopes are correct (growing brand).
        # Population mean near log($500) = mid-range of true slopes.

        mu_log_trend    = pm.Normal("mu_log_trend",    mu=np.log(500), sigma=0.8)
        sigma_log_trend = pm.HalfNormal("sigma_log_trend", sigma=0.5)

        # ── Revenue noise σ ────────────────────────────────────────────────────
        # Separate σ per region: noise scales with market size.
        # HalfNormal(50_000) is diffuse; data-driven estimate expected.

        sigma_rev = pm.HalfNormal("sigma_rev", sigma=50_000, shape=R)

        # ── Fourier seasonality coefficients ───────────────────────────────────
        # Partial pooling across regions: population mean ~ Normal(0, 30_000),
        # per-region offsets add additional flexibility.
        # Shape: (4,) for population mean, (R, 4) for per-region offsets.

        mu_fourier    = pm.Normal("mu_fourier",    mu=0, sigma=30_000, shape=4)
        sigma_fourier = pm.HalfNormal("sigma_fourier", sigma=15_000, shape=4)
        z_fourier     = pm.Normal("z_fourier", mu=0, sigma=1, shape=(R, 4))
        fourier_coefs = pm.Deterministic(
            "fourier_coefs", mu_fourier[None, :] + sigma_fourier[None, :] * z_fourier
        )  # (R, 4)

        # ── Holiday deltas ─────────────────────────────────────────────────────
        # Pooled across regions: all regions experience the same promotional
        # calendar (Black Friday, spring launch, etc.) with shared direction.
        # HalfNormal on σ: cross-region variation exists but is moderate.

        mu_holidays    = pm.Normal("mu_holidays",    mu=0, sigma=0.25, shape=len(HOLIDAY_WEEKS))
        sigma_holidays = pm.HalfNormal("sigma_holidays", sigma=0.10,  shape=len(HOLIDAY_WEEKS))
        z_holidays     = pm.Normal("z_holidays", mu=0, sigma=1, shape=(R, len(HOLIDAY_WEEKS)))
        holiday_deltas = pm.Deterministic(
            "holiday_deltas",
            mu_holidays[None, :] + sigma_holidays[None, :] * z_holidays
        )  # (R, H)


        # ════════════════════════════════════════════════════════════════════
        # NON-CENTERED PER-REGION PARAMETERS
        # ════════════════════════════════════════════════════════════════════

        # ── Adstock offsets ────────────────────────────────────────────────────
        z_alpha_tv   = pm.Normal("z_alpha_tv",   mu=0, sigma=1, shape=R)
        z_alpha_ps   = pm.Normal("z_alpha_ps",   mu=0, sigma=1, shape=R)
        z_alpha_so   = pm.Normal("z_alpha_so",   mu=0, sigma=1, shape=R)
        z_alpha_disp = pm.Normal("z_alpha_disp", mu=0, sigma=1, shape=R)

        alpha_tv   = pm.Deterministic("alpha_tv",
            pt.clip(mu_alpha_tv   + sigma_alpha_tv   * z_alpha_tv,   0.01, 0.99))
        alpha_ps   = pm.Deterministic("alpha_ps",
            pt.clip(mu_alpha_ps   + sigma_alpha_ps   * z_alpha_ps,   0.01, 0.99))
        alpha_so   = pm.Deterministic("alpha_so",
            pt.clip(mu_alpha_so   + sigma_alpha_so   * z_alpha_so,   0.01, 0.99))
        alpha_disp = pm.Deterministic("alpha_disp",
            pt.clip(mu_alpha_disp + sigma_alpha_disp * z_alpha_disp, 0.01, 0.99))

        alphas = {"tv": alpha_tv, "paid_search": alpha_ps,
                  "social": alpha_so, "display": alpha_disp}

        # ── Hill k offsets (log-normal NCP) ───────────────────────────────────
        z_k_tv   = pm.Normal("z_k_tv",   mu=0, sigma=1, shape=R)
        z_k_ps   = pm.Normal("z_k_ps",   mu=0, sigma=1, shape=R)
        z_k_so   = pm.Normal("z_k_so",   mu=0, sigma=1, shape=R)
        z_k_disp = pm.Normal("z_k_disp", mu=0, sigma=1, shape=R)

        k_tv   = pm.Deterministic("k_tv",   pt.exp(mu_log_k_tv   + sigma_log_k_tv   * z_k_tv))
        k_ps   = pm.Deterministic("k_ps",   pt.exp(mu_log_k_ps   + sigma_log_k_ps   * z_k_ps))
        k_so   = pm.Deterministic("k_so",   pt.exp(mu_log_k_so   + sigma_log_k_so   * z_k_so))
        k_disp = pm.Deterministic("k_disp", pt.exp(mu_log_k_disp + sigma_log_k_disp * z_k_disp))

        ks = {"tv": k_tv, "paid_search": k_ps, "social": k_so, "display": k_disp}

        # ── Hill ec offsets ────────────────────────────────────────────────────
        z_ec_tv   = pm.Normal("z_ec_tv",   mu=0, sigma=1, shape=R)
        z_ec_ps   = pm.Normal("z_ec_ps",   mu=0, sigma=1, shape=R)
        z_ec_so   = pm.Normal("z_ec_so",   mu=0, sigma=1, shape=R)
        z_ec_disp = pm.Normal("z_ec_disp", mu=0, sigma=1, shape=R)

        ec_tv   = pm.Deterministic("ec_tv",
            pt.clip(mu_ec_tv   + sigma_ec_tv   * z_ec_tv,   0.01, 0.99))
        ec_ps   = pm.Deterministic("ec_ps",
            pt.clip(mu_ec_ps   + sigma_ec_ps   * z_ec_ps,   0.01, 0.99))
        ec_so   = pm.Deterministic("ec_so",
            pt.clip(mu_ec_so   + sigma_ec_so   * z_ec_so,   0.01, 0.99))
        ec_disp = pm.Deterministic("ec_disp",
            pt.clip(mu_ec_disp + sigma_ec_disp * z_ec_disp, 0.01, 0.99))

        ecs = {"tv": ec_tv, "paid_search": ec_ps, "social": ec_so, "display": ec_disp}

        # ── Beta offsets (log-normal NCP) ──────────────────────────────────────
        z_beta_tv   = pm.Normal("z_beta_tv",   mu=0, sigma=1, shape=R)
        z_beta_ps   = pm.Normal("z_beta_ps",   mu=0, sigma=1, shape=R)
        z_beta_so   = pm.Normal("z_beta_so",   mu=0, sigma=1, shape=R)
        z_beta_disp = pm.Normal("z_beta_disp", mu=0, sigma=1, shape=R)

        beta_tv   = pm.Deterministic("beta_tv",
            pt.exp(mu_log_beta_tv   + sigma_log_beta_tv   * z_beta_tv))
        beta_ps   = pm.Deterministic("beta_ps",
            pt.exp(mu_log_beta_ps   + sigma_log_beta_ps   * z_beta_ps))
        beta_so   = pm.Deterministic("beta_so",
            pt.exp(mu_log_beta_so   + sigma_log_beta_so   * z_beta_so))
        beta_disp = pm.Deterministic("beta_disp",
            pt.exp(mu_log_beta_disp + sigma_log_beta_disp * z_beta_disp))

        betas = {"tv": beta_tv, "paid_search": beta_ps,
                 "social": beta_so, "display": beta_disp}

        # ── Intercept offsets (log-normal NCP) ────────────────────────────────
        z_intercept = pm.Normal("z_intercept", mu=0, sigma=1, shape=R)
        intercept   = pm.Deterministic("intercept",
            pt.exp(mu_log_intercept + sigma_log_intercept * z_intercept))   # (R,)

        # ── Trend slope offsets (log-normal NCP) ──────────────────────────────
        z_trend    = pm.Normal("z_trend",    mu=0, sigma=1, shape=R)
        trend_slope = pm.Deterministic("trend_slope",
            pt.exp(mu_log_trend + sigma_log_trend * z_trend))   # (R,)


        # ════════════════════════════════════════════════════════════════════
        # DETERMINISTIC QUANTITIES — built region by region, then stacked
        # ════════════════════════════════════════════════════════════════════

        region_mus = []

        for r, region in enumerate(REGIONS):

            # ── Baseline ──────────────────────────────────────────────────────
            # intercept[r] and trend_slope[r] are (R,) deterministics — slice.
            trend_r      = intercept[r] + trend_slope[r] * t_std   # (T,)
            seasonal_r   = pt.dot(fourier, fourier_coefs[r])        # (T,)
            holiday_r    = pt.dot(holiday_matrix, holiday_deltas[r]) * intercept[r]  # (T,)
            baseline_r   = pm.Deterministic(
                f"baseline_{region}", trend_r + seasonal_r + holiday_r
            )

            # ── Media contributions ───────────────────────────────────────────
            region_contribs = []
            for ch in CHANNELS:
                lag_mat_r = pt.as_tensor_variable(
                    inputs["lag_matrices"][ch][r].astype("float64")
                )   # (T, MAX_LAG)
                p95_r = inputs["p95"][ch][r]   # fixed scalar

                adstock_r      = pytensor_geometric_adstock_vec(
                    lag_mat_r, inputs["lags"], alphas[ch][r]
                )   # (T,)
                adstock_norm_r = adstock_r / p95_r
                saturated_r    = pytensor_hill(adstock_norm_r, ks[ch][r], ecs[ch][r])
                contrib_r      = pm.Deterministic(
                    f"contrib_{ch}_{region}", betas[ch][r] * saturated_r
                )   # (T,)
                region_contribs.append(contrib_r)

            total_media_r = sum(region_contribs)
            mu_r          = baseline_r + total_media_r   # (T,)
            region_mus.append(mu_r)

        # Stack all regions: (R, T)
        mu = pm.Deterministic("mu", pt.stack(region_mus, axis=0))   # (R, T)

        # ── Likelihood ────────────────────────────────────────────────────────
        # sigma_rev is (R,) — broadcast to (R, T) via [:, None]
        revenue_rv = pm.Normal(
            "revenue",
            mu=mu,
            sigma=sigma_rev[:, None],
            observed=revenue_obs,
        )

    return model


