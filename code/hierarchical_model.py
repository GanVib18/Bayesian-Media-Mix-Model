# 10. POSTERIOR CONTRIBUTION DECOMPOSITION
# ══════════════════════════════════════════════════════════════════════════════

def plot_posterior_contributions(idata: az.InferenceData,
                                  inputs: dict,
                                  save_path: str = "outputs/fig_posterior_contributions_hier.png"):
    """
    Plot posterior mean channel contributions vs. observed revenue for all regions.

    Two panels per region:
      Top:    Stacked area chart — baseline + per-channel contributions.
      Bottom: Posterior predicted revenue (mean + 94% band) vs. observed.

    This is the key business-readable output: how much is each channel contributing
    to revenue, with honest uncertainty (credible bands) around the decomposition.
    """
    print("\n  Plotting posterior contributions...")

    posterior = idata.posterior
    dates     = pd.to_datetime(inputs["dates"])
    T         = inputs["T"]

    fig, axes = plt.subplots(N_REGIONS, 2, figsize=(18, 5 * N_REGIONS), sharex=False)
    fig.suptitle(
        "MapleThread — Posterior Revenue Decomposition (All Regions)\n"
        "Left: stacked contributions  |  Right: posterior predicted vs. observed",
        fontsize=13, fontweight="bold", y=1.005,
    )

    for r, region in enumerate(REGIONS):
        observed = inputs["revenue"][r]
        color    = PALETTE[region]

        # ── Left: stacked contributions ───────────────────────────────────────
        ax_left = axes[r, 0]

        baseline_post = posterior[f"baseline_{region}"].values.reshape(-1, T)
        baseline_mean = baseline_post.mean(axis=0)
        ax_left.fill_between(dates, 0, baseline_mean, alpha=0.5,
                             color=PALETTE["baseline"], label="Baseline")
        bottom = baseline_mean.copy()

        for ch in CHANNELS:
            contrib_post = posterior[f"contrib_{ch}_{region}"].values.reshape(-1, T)
            c_mean = contrib_post.mean(axis=0)
            ax_left.fill_between(dates, bottom, bottom + c_mean, alpha=0.75,
                                 color=PALETTE[ch], label=CHANNEL_LABELS[ch])
            bottom = bottom + c_mean

        ax_left.plot(dates, observed, color="white", lw=0.8, alpha=0.5,
                     label="Observed revenue")
        ax_left.set_title(f"{REGION_LABELS[region]} — Contribution decomposition",
                          fontsize=10, fontweight="bold", color=color)
        ax_left.set_ylabel("Revenue ($)")
        ax_left.yaxis.set_major_formatter(
            mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
        ax_left.legend(loc="upper left", fontsize=7, ncol=3, framealpha=0.7)

        # ── Right: posterior predicted vs. observed ───────────────────────────
        ax_right = axes[r, 1]

        # mu shape: (chains, draws, R, T) — select region r
        mu_post = posterior["mu"].values[:, :, r, :].reshape(-1, T)
        mu_mean = mu_post.mean(axis=0)
        mu_lo   = np.percentile(mu_post,  3, axis=0)
        mu_hi   = np.percentile(mu_post, 97, axis=0)

        ax_right.fill_between(dates, mu_lo, mu_hi, alpha=0.25, color="#4361EE",
                              label="94% posterior band")
        ax_right.plot(dates, mu_mean,  color="#4361EE", lw=1.5, label="Posterior mean")
        ax_right.plot(dates, observed, color="#E63946", lw=1.2, alpha=0.85,
                      label="Observed revenue")
        ax_right.set_title(f"{REGION_LABELS[region]} — Predicted vs. observed",
                           fontsize=10, fontweight="bold", color=color)
        ax_right.set_ylabel("Revenue ($)")
        ax_right.yaxis.set_major_formatter(
            mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
        ax_right.legend(loc="upper left", fontsize=7)

    plt.tight_layout()
    plt.savefig(save_path, dpi=130, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Posterior contributions saved: {save_path}")


