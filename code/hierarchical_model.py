def _build_lag_matrix(spend: np.ndarray, max_lag: int = MAX_LAG) -> np.ndarray:
    """
    Build (T, max_lag) lag matrix from a 1-D spend array.

    lag_matrix[t, l] = spend[t - l]  (zero-padded for t < l)

    Enables vectorised geometric adstock as a single dot product inside PyMC:
        adstock[t] = lag_matrix[t] · (alpha^0, alpha^1, ..., alpha^{L-1})
    """
    T = len(spend)
    lag_mat = np.zeros((T, max_lag), dtype=float)
    for l in range(max_lag):
        lag_mat[l:, l] = spend[:T - l]
    return lag_mat


def build_hierarchical_inputs(raw_df: pd.DataFrame) -> dict:
    """
    Construct all numpy arrays the hierarchical PyMC model needs.

    Arrays are indexed [region, time] or [region, time, lag] so the model
    can operate over all regions simultaneously.

    Key outputs
    -----------
    revenue       : (R, T)          — observed weekly revenue
    lag_matrices  : {ch: (R, T, L)} — precomputed lag matrices per channel
    p95           : {ch: (R,)}      — p95 normalisation constants per channel/region
    fourier       : (T, 4)          — Fourier features (same for all regions / same dates)
    holiday_matrix: (T, H)          — holiday indicator matrix
    t_std         : (T,)            — standardised time index [0, 1]
    lags          : (L,)            — integer lag indices [0..L-1]
    """
    T    = N_WEEKS
    lags = np.arange(MAX_LAG, dtype=float)

    # ── Time and Fourier features (identical across regions — same date range) ──
    t     = np.arange(T, dtype=float)
    t_std = t / (T - 1)

    fourier = np.column_stack([
        np.sin(2 * np.pi * 1 * t / 52),
        np.cos(2 * np.pi * 1 * t / 52),
        np.sin(2 * np.pi * 2 * t / 52),
        np.cos(2 * np.pi * 2 * t / 52),
    ])  # (T, 4)

    # Use the first region's dates for holiday matrix (same calendar for all)
    first_region_df = raw_df[raw_df["region"] == REGIONS[0]].reset_index(drop=True)
    week_of_year    = first_region_df["date"].dt.isocalendar().week.values.astype(int)
    holiday_matrix  = np.zeros((T, len(HOLIDAY_WEEKS)), dtype=float)
    for j, hw in enumerate(HOLIDAY_WEEKS):
        holiday_matrix[:, j] = (week_of_year == hw).astype(float)

    # ── Per-region spend preprocessing ─────────────────────────────────────────
    revenue_list      = []
    lag_matrices_list = {ch: [] for ch in CHANNELS}
    p95_list          = {ch: [] for ch in CHANNELS}
    dates_list        = []

    for region in REGIONS:
        df = raw_df[raw_df["region"] == region].reset_index(drop=True)
        revenue_list.append(df["revenue"].values.astype(float))
        dates_list.append(df["date"].values)

        for ch in CHANNELS:
            spend   = df[f"spend_{ch}"].values.astype(float)
            lag_mat = _build_lag_matrix(spend, MAX_LAG)
            lag_matrices_list[ch].append(lag_mat)

            # p95 normalisation: computed at the true alpha so Hill ec stays
            # interpretable on [0, 1]. Same logic as Phase 3 — fixed constant.
            alpha_true = TRUE_PARAMS["adstock"][ch]
            weights    = alpha_true ** lags
            ads_true   = lag_mat @ weights
            p95_list[ch].append(float(np.percentile(ads_true, 95)))

    revenue = np.stack(revenue_list)  # (R, T)

    # Stack to (R, T, L) for lag matrices, (R,) for p95
    lag_matrices = {ch: np.stack(lag_matrices_list[ch]) for ch in CHANNELS}
    p95          = {ch: np.array(p95_list[ch])           for ch in CHANNELS}

    return {
        "R":              N_REGIONS,
        "T":              T,
        "t":              t,
        "t_std":          t_std,
        "fourier":        fourier,
        "holiday_matrix": holiday_matrix,
        "week_of_year":   week_of_year,
        "revenue":        revenue,
        "lag_matrices":   lag_matrices,
        "p95":            p95,
        "lags":           lags,
        "dates":          dates_list[0],   # same for all regions
    }


