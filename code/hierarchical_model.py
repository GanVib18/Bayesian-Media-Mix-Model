def run_prior_predictive(model: pm.Model,
                          inputs: dict,
                          n_samples: int = 300,
                          save_path: str = "outputs/fig_prior_predictive_hier.png"):
    """
    Sample from the prior only and plot implied revenue distributions for all regions.

    A well-calibrated prior should:
      - Comfortably cover each region's observed revenue range
      - Not put appreciable mass below $0 or above $5M (for the smallest markets,
        upper bounds are much lower — Australia max ~$200K)
    """
    print("\n  Running prior predictive check...")
    with model:
        prior_pred = pm.sample_prior_predictive(samples=n_samples, random_seed=RANDOM_SEED)

    # prior_predictive["revenue"] shape: (1, n_samples, R, T) — squeeze chain dim
    prior_draws = prior_pred.prior_predictive["revenue"].values[0]   # (n_samples, R, T)
    dates        = pd.to_datetime(inputs["dates"])

    fig, axes = plt.subplots(N_REGIONS, 2, figsize=(16, 4 * N_REGIONS))
    fig.suptitle(
        "Prior Predictive Check — All Regions\n"
        "Do the hierarchical priors allow plausible revenue trajectories?",
        fontsize=13, fontweight="bold",
    )

    for r, region in enumerate(REGIONS):
        draws_r  = prior_draws[:, r, :]   # (n_samples, T)
        observed = inputs["revenue"][r]

        p05 = np.percentile(draws_r,  5, axis=0)
        p25 = np.percentile(draws_r, 25, axis=0)
        p50 = np.percentile(draws_r, 50, axis=0)
        p75 = np.percentile(draws_r, 75, axis=0)
        p95 = np.percentile(draws_r, 95, axis=0)

        color = PALETTE[region]

        # ── Fan chart ─────────────────────────────────────────────────────────
        ax = axes[r, 0]
        ax.fill_between(dates, p05, p95, alpha=0.20, color=color, label="5–95th pct")
        ax.fill_between(dates, p25, p75, alpha=0.35, color=color, label="25–75th pct")
        ax.plot(dates, p50,      color=color,    lw=1.5, label="Median prior")
        ax.plot(dates, observed, color="#1D3557", lw=1.2, alpha=0.9, label="Observed")
        ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
        ax.set_title(f"{REGION_LABELS[region]} — Prior fan", fontsize=10, color=color,
                     fontweight="bold")
        ax.set_ylabel("Revenue")
        ax.legend(fontsize=7, loc="upper left", ncol=2)

        # ── Marginal histogram ────────────────────────────────────────────────
        ax = axes[r, 1]
        flat    = draws_r.flatten()
        clipped = flat[(flat > -2e6) & (flat < observed.max() * 5)]
        ax.hist(clipped / 1e3, bins=60, color=color, alpha=0.65,
                edgecolor="white", linewidth=0.3)
        obs_min, obs_max = observed.min() / 1e3, observed.max() / 1e3
        ax.axvspan(obs_min, obs_max, alpha=0.25, color="#1D3557",
                   label=f"Observed range\n(${obs_min:.0f}K–${obs_max:.0f}K)")
        ax.axvline(0, color="black", lw=1.2, linestyle="--", alpha=0.6)
        ax.set_xlabel("Revenue ($K)")
        ax.set_ylabel("Count")
        ax.set_title("Marginal prior distribution", fontsize=10)
        ax.legend(fontsize=7)

        pct_neg  = (draws_r < 0).mean() * 100
        print(f"    {REGION_LABELS[region]:>15s}: "
              f"median prior ${np.median(draws_r):>9,.0f} | "
              f"{pct_neg:.1f}% draws < $0")

    plt.tight_layout()
    plt.savefig(save_path, dpi=130, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Prior predictive saved: {save_path}")

    return prior_pred


