def plot_parameter_recovery(idata: az.InferenceData,
                             save_path: str = "outputs/fig_parameter_recovery.png"):
    """
    Plot posterior distributions against true parameter values.

    This is the core model validation step. For each key parameter, we plot:
      - The marginal posterior density (KDE from ArviZ)
      - A vertical line marking the true DGP value
      - The 94% HDI (ArviZ default)

    A well-identified model should have the true value inside the 94% HDI
    for most parameters. Near-perfect recovery on all parameters would be
    suspicious (overfit); some uncertainty is expected and correct.

    Parameters shown
    ----------------
    Adstock decays (α), Hill slopes (k), Hill half-saturation (ec),
    channel betas (β), intercept, trend_slope, sigma.

    Note on beta recovery
    ----------------------
    β and k are partially identified — a high β with low k can produce
    similar predicted revenue to a lower β with higher k. Expect wider
    posteriors here and possible mild bias, which is a genuine model
    limitation to discuss in the writeup.
    """
    print("\n  Plotting parameter recovery...")

    # ── True values for each recoverable scalar parameter ────────────────────
    true_values = {
        "intercept":   TRUE_PARAMS["intercept"],
        # trend_slope: posterior is in ($/unit t_std). True equivalent = 950 × 155.
        # Both sides are multiplied by (N_WEEKS-1) so the comparison is consistent.
        "trend_slope": TRUE_PARAMS["trend_slope"] * (N_WEEKS - 1),
        "sigma":       TRUE_PARAMS["noise_std"],
        "alpha_tv":    TRUE_PARAMS["adstock"]["tv"],
        "alpha_ps":    TRUE_PARAMS["adstock"]["paid_search"],
        "alpha_so":    TRUE_PARAMS["adstock"]["social"],
        "alpha_disp":  TRUE_PARAMS["adstock"]["display"],
        "k_tv":        TRUE_PARAMS["hill_k"]["tv"],
        "k_ps":        TRUE_PARAMS["hill_k"]["paid_search"],
        "k_so":        TRUE_PARAMS["hill_k"]["social"],
        "k_disp":      TRUE_PARAMS["hill_k"]["display"],
        "ec_tv":       TRUE_PARAMS["hill_ec"]["tv"],
        "ec_ps":       TRUE_PARAMS["hill_ec"]["paid_search"],
        "ec_so":       TRUE_PARAMS["hill_ec"]["social"],
        "ec_disp":     TRUE_PARAMS["hill_ec"]["display"],
        "beta_tv":     TRUE_PARAMS["beta"]["tv"],
        "beta_ps":     TRUE_PARAMS["beta"]["paid_search"],
        "beta_so":     TRUE_PARAMS["beta"]["social"],
        "beta_disp":   TRUE_PARAMS["beta"]["display"],
    }

    param_labels = {
        "intercept":   "Intercept ($)",
        "trend_slope": "Trend slope (total $ over 3yr)",
        "sigma":       "Noise σ ($)",
        "alpha_tv":    "α TV",
        "alpha_ps":    "α Paid Search",
        "alpha_so":    "α Social",
        "alpha_disp":  "α Display",
        "k_tv":        "k TV",
        "k_ps":        "k Paid Search",
        "k_so":        "k Social",
        "k_disp":      "k Display",
        "ec_tv":       "ec TV",
        "ec_ps":       "ec Paid Search",
        "ec_so":       "ec Social",
        "ec_disp":     "ec Display",
        "beta_tv":     "β TV ($)",
        "beta_ps":     "β Paid Search ($)",
        "beta_so":     "β Social ($)",
        "beta_disp":   "β Display ($)",
    }

    param_colors = {
        "intercept": "#6A4C93", "trend_slope": "#6A4C93", "sigma": "#6A4C93",
        "alpha_tv": PALETTE["tv"], "alpha_ps": PALETTE["paid_search"],
        "alpha_so": PALETTE["social"], "alpha_disp": PALETTE["display"],
        "k_tv": PALETTE["tv"], "k_ps": PALETTE["paid_search"],
        "k_so": PALETTE["social"], "k_disp": PALETTE["display"],
        "ec_tv": PALETTE["tv"], "ec_ps": PALETTE["paid_search"],
        "ec_so": PALETTE["social"], "ec_disp": PALETTE["display"],
        "beta_tv": PALETTE["tv"], "beta_ps": PALETTE["paid_search"],
        "beta_so": PALETTE["social"], "beta_disp": PALETTE["display"],
    }

    params = list(true_values.keys())
    n_params = len(params)
    n_cols = 4
    n_rows = int(np.ceil(n_params / n_cols))

    fig, axes = plt.subplots(n_rows, n_cols, figsize=(18, n_rows * 3.2))
    axes_flat = axes.flatten()

    posterior = idata.posterior

    for i, param in enumerate(params):
        ax = axes_flat[i]
        color = param_colors[param]

        # Extract posterior samples (all chains, all draws)
        samples = posterior[param].values.flatten()

        # Special case: trend_slope was estimated on t_std ∈ [0,1], so the
        # posterior is in units of ($/unit of t_std). Multiply by (T-1) to
        # convert back to $/week for a fair comparison to the true value.
        if param == "trend_slope":
            samples = samples * (N_WEEKS - 1)

        # KDE via ArviZ
        az.plot_kde(
            samples,
            ax=ax,
            plot_kwargs={"color": color, "linewidth": 2},
            fill_kwargs={"alpha": 0.25, "color": color},
        )

        # True value line
        true_val = true_values[param]
        ax.axvline(true_val, color="black", lw=2, linestyle="--",
                   label=f"True: {true_val:,.0f}" if abs(true_val) > 1 else f"True: {true_val:.3f}")

        # 94% HDI
        hdi = az.hdi(samples, hdi_prob=0.94)
        ax.axvspan(hdi[0], hdi[1], alpha=0.10, color=color, label="94% HDI")

        # Check recovery
        inside_hdi = hdi[0] <= true_val <= hdi[1]
        recovery_marker = "✓" if inside_hdi else "✗"
        ax.set_title(f"{param_labels[param]}  {recovery_marker}", fontsize=8.5,
                     fontweight="bold", color=color)
        ax.tick_params(labelsize=7)
        ax.legend(fontsize=6.5, loc="upper right")

        # Format x-axis for dollar values
        if param in ("intercept", "trend_slope", "sigma", "beta_tv",
                     "beta_ps", "beta_so", "beta_disp"):
            ax.xaxis.set_major_formatter(
                mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K")
            )

    # Hide unused subplots
    for j in range(n_params, len(axes_flat)):
        axes_flat[j].set_visible(False)

    # Count recovery rate
    n_recovered = sum(
        az.hdi(
            (posterior[p].values.flatten() * (N_WEEKS - 1)
             if p == "trend_slope"
             else posterior[p].values.flatten()),
            hdi_prob=0.94
        )[0] <= true_values[p] <=
        az.hdi(
            (posterior[p].values.flatten() * (N_WEEKS - 1)
             if p == "trend_slope"
             else posterior[p].values.flatten()),
            hdi_prob=0.94
        )[1]
        for p in params
    )

    fig.suptitle(
        f"Parameter Recovery — Canada  ({n_recovered}/{n_params} true values inside 94% HDI)\n"
        "Black dashed = true DGP value  |  ✓ = inside HDI  |  ✗ = outside HDI",
        fontsize=12, fontweight="bold", y=1.01,
    )
    plt.tight_layout()
    plt.savefig(save_path, dpi=130, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Parameter recovery saved: {save_path}")
    print(f"  Recovery rate: {n_recovered}/{n_params} parameters inside 94% HDI")


