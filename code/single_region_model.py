def build_model_inputs(raw_df: pd.DataFrame) -> dict:
    """
    Construct all numpy arrays the PyMC model needs.

    Preprocessing steps
    -------------------
    1. Time index t = 0, 1, …, 155 (standardised to [0, 1] for trend prior).
    2. Fourier features for annual and semi-annual cycles (4 columns).
    3. Holiday indicator matrix (T × 12) — one column per holiday week.
    4. Geometric adstock per channel, normalised by p95 (fixed constant,
       computed on observed data — this is what the model will see).

    Notes on adstock normalisation
    -------------------------------
    The DGP normalises each channel's adstock by its 95th percentile before
    applying Hill. We replicate this exactly: compute p95 on the observed
    spend series, store it as a fixed constant, and use it in both the
    preprocessing and the PyTensor adstock node inside the model.
    """
    T = len(raw_df)
    t = np.arange(T, dtype=float)

    # ── Trend (standardised for numerical stability) ──────────────────────────
    # The model estimates trend_slope in units of revenue-per-standardised-week.
    # We undo the standardisation when comparing to true_slope in recovery plots.
    t_std = t / (T - 1)  # maps [0, 155] → [0, 1]

    # ── Fourier seasonality features ─────────────────────────────────────────
    # Two harmonics (annual + semi-annual): sin1, cos1, sin2, cos2
    fourier = np.column_stack([
        np.sin(2 * np.pi * 1 * t / 52),
        np.cos(2 * np.pi * 1 * t / 52),
        np.sin(2 * np.pi * 2 * t / 52),
        np.cos(2 * np.pi * 2 * t / 52),
    ])  # shape (T, 4)

    # ── Holiday indicator matrix ──────────────────────────────────────────────
    week_of_year = raw_df["date"].dt.isocalendar().week.values.astype(int)
    holiday_matrix = np.zeros((T, len(HOLIDAY_WEEKS)), dtype=float)
    for j, hw in enumerate(HOLIDAY_WEEKS):
        holiday_matrix[:, j] = (week_of_year == hw).astype(float)
    # holiday_matrix[t, j] = 1 if week t falls in holiday j, else 0

    # ── Adstock preprocessing (numpy, pre-model) ──────────────────────────────
    # We pre-apply geometric adstock at the TRUE alpha values to generate the
    # normalisation constants (p95). During model fitting, adstock is recomputed
    # inside the PyMC model using PyTensor scan — the p95 constants are then
    # used to normalise that symbolic adstock.
    #
    # This is equivalent to what the DGP does and ensures the Hill ec parameter
    # remains in a [0,1]-interpretable range during sampling.
    # Adstock: precomputed lag matrices (vectorised, no scan)
    #
    # Instead of computing adstock inside the model with a recursive loop
    # (pytensor.scan), we precompute a lagged spend matrix of shape (T, MAX_LAG)
    # where column l contains spend shifted l periods into the past (zero-padded).
    #
    # Inside the model, adstock is then a single matrix-vector product:
    #
    #     adstock[t] = sum_{l=0}^{L-1} alpha^l * spend[t-l]
    #                = lag_matrix[t] . (alpha^0, alpha^1, ..., alpha^{L-1})
    #
    # This is mathematically equivalent to geometric adstock (truncation error
    # is alpha^L, which is negligible for L=52 even at alpha=0.75: ~3e-7).
    #
    # The lag matrix is a fixed numpy constant — the only symbolic operation
    # inside PyMC is the dot product with the weight vector, which PyTensor
    # vectorises efficiently and GPUs handle natively. No scan, no loop.
    MAX_LAG = 52
    lags = np.arange(MAX_LAG, dtype=float)   # [0, 1, 2, ..., 51]

    raw_spend     = {}
    lag_matrices  = {}
    p95_constants = {}

    for ch in CHANNELS:
        spend = raw_df[f"spend_{ch}"].values.astype(float)
        raw_spend[ch] = spend

        # Build (T, MAX_LAG) lag matrix: column l = spend shifted l steps back
        lag_mat = np.zeros((T, MAX_LAG), dtype=float)
        for l in range(MAX_LAG):
            lag_mat[l:, l] = spend[:T - l]
        lag_matrices[ch] = lag_mat

        # p95 normalisation constant: computed at true alpha for scale reference.
        # The model sees adstock / p95, keeping Hill ec interpretable on [0, 1].
        alpha_true = TRUE_PARAMS["adstock"][ch]
        weights    = alpha_true ** lags
        ads_true   = lag_mat @ weights
        p95_constants[ch] = float(np.percentile(ads_true, 95))

    return {
        "T":              T,
        "t":              t,
        "t_std":          t_std,
        "fourier":        fourier,
        "holiday_matrix": holiday_matrix,
        "week_of_year":   week_of_year,
        "revenue":        raw_df["revenue"].values.astype(float),
        "raw_spend":      raw_spend,
        "lag_matrices":   lag_matrices,
        "lags":           lags,
        "p95":            p95_constants,
        "dates":          raw_df["date"].values,
    }


def _numpy_geometric_adstock(spend: np.ndarray, alpha: float) -> np.ndarray:
    """Pure numpy geometric adstock — used only for preprocessing."""
    ads = np.empty_like(spend, dtype=float)
    ads[0] = spend[0]
    for t in range(1, len(spend)):
        ads[t] = spend[t] + alpha * ads[t - 1]
    return ads


