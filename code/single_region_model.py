# 3. PYTENSOR MEDIA TRANSFORMS (vectorised, no scan)
# ══════════════════════════════════════════════════════════════════════════════

def pytensor_geometric_adstock_vec(lag_matrix: pt.TensorVariable,
                                    lags: np.ndarray,
                                    alpha: pt.TensorVariable) -> pt.TensorVariable:
    """
    Vectorised geometric adstock via lag-matrix dot product — no scan required.

    adstock[t] = sum_{l=0}^{L-1} alpha^l * spend[t-l]
               = lag_matrix[t] . weight_vector

    where weight_vector[l] = alpha^l, shape (MAX_LAG,).

    lag_matrix is a fixed (T, MAX_LAG) numpy array precomputed in
    build_model_inputs. Inside PyMC, only the dot product is symbolic,
    making this ~100x faster than pytensor.scan for 156 time steps.

    Parameters
    ----------
    lag_matrix : pt.TensorVariable, shape (T, MAX_LAG)
        Precomputed lagged spend matrix (fixed data constant).
    lags : np.ndarray, shape (MAX_LAG,)
        Integer lag indices [0, 1, ..., MAX_LAG-1].
    alpha : pt.TensorVariable, scalar
        Symbolic decay rate in [0, 1).

    Returns
    -------
    pt.TensorVariable, shape (T,)
        Adstock time series.
    """
    weights = alpha ** pt.as_tensor_variable(lags)   # (MAX_LAG,) symbolic
    return pt.dot(lag_matrix, weights)                # (T,)


def pytensor_hill(x: pt.TensorVariable,
                  k: pt.TensorVariable,
                  ec: pt.TensorVariable) -> pt.TensorVariable:
    """
    Hill saturation: S(x) = x^k / (x^k + ec^k)

    Numerically safe: replaces x=0 with a small epsilon so gradients are
    well-defined. The result is still effectively 0 at x≈0.
    """
    safe_x = pt.switch(pt.eq(x, 0.0), 1e-10, x)
    return safe_x**k / (safe_x**k + ec**k)


