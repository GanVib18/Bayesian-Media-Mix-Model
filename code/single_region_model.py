def build_model(inputs: dict) -> pm.Model:
    """
    Build the single-region Bayesian MMM for Canada.

    Model structure
    ---------------
    Revenue[t] = Baseline[t]
               + Σ_c β_c × Hill(Adstock(spend_c[t]) / p95_c ; k_c, ec_c)
               + ε[t]

    where ε[t] ~ Normal(0, σ²)

    Baseline[t] = intercept
                + trend_slope × t_std[t]
                + A1×sin1[t] + B1×cos1[t] + A2×sin2[t] + B2×cos2[t]
                + Σ_j δ_j × holiday_matrix[t, j]

    Prior justifications (each commented inline)
    --------------------------------------------
    All revenue quantities are scaled to Canada's range:
        mean ~$780K, std ~$100K, min ~$540K, max ~$1.15M
    """
    T              = inputs["T"]
    t_std          = pt.as_tensor_variable(inputs["t_std"].astype("float64"))
    fourier        = pt.as_tensor_variable(inputs["fourier"].astype("float64"))
    holiday_matrix = pt.as_tensor_variable(inputs["holiday_matrix"].astype("float64"))
    revenue_obs    = inputs["revenue"].astype("float64")

    with pm.Model() as model:

        # ── PRIORS: Baseline ─────────────────────────────────────────────────

        # Intercept: Canada's weekly baseline revenue is ~$620K with growth.
        # HalfNormal(1_000_000) puts 99% of prior mass below ~$2.3M — diffuse
        # but bounded positive (revenue can't be negative).
        intercept = pm.HalfNormal("intercept", sigma=1_000_000)

        # Trend slope: revenue grows ~$950/week at true params. Over 155 weeks
        # (t_std range = 1), trend contribution is ~$147K total.
        # HalfNormal(300_000) is diffuse but enforces a positive trend assumption
        # (outdoor brand growing over 3 years is reasonable).
        trend_slope = pm.HalfNormal("trend_slope", sigma=300_000)

        # Fourier coefficients: each amplitude is ~[-25K, +40K] at ground truth.
        # Normal(0, 50_000) covers this range well while allowing both signs.
        # The prior is symmetric — we have no directional prior on seasonality.
        fourier_coefs = pm.Normal("fourier_coefs", mu=0, sigma=50_000, shape=4)

        # Holiday deltas: revenue lift/drag around key retail weeks.
        # True multipliers range from 0.90 (summer trough) to 1.75 (Black Friday).
        # We model as δ_j ~ Normal(0, 0.3) centred at zero (no lift assumed a priori).
        # The final holiday effect is baseline × (1 + Σ δ_j × I[holiday j]).
        holiday_deltas = pm.Normal("holiday_deltas", mu=0, sigma=0.3,
                                   shape=len(HOLIDAY_WEEKS))

        # ── PRIORS: Noise ────────────────────────────────────────────────────

        # Revenue noise: true DGP adds Gaussian noise with std ~$28K, plus
        # unmodelled variation. HalfNormal(100_000) is diffuse enough to let
        # the data speak, while being bounded positive.
        sigma = pm.HalfNormal("sigma", sigma=100_000)

        # ── PRIORS: Adstock decay rates ───────────────────────────────────────

        # Alpha lives in [0,1) — Beta distribution is the natural choice.
        # Priors informed by channel type:
        #   TV:          long carryover → Beta(8, 3)  → mean=0.73, mode≈0.78
        #   Paid Search: short          → Beta(2, 8)  → mean=0.20, mode≈0.13
        #   Social:      medium         → Beta(5, 6)  → mean=0.45, mode≈0.44
        #   Display:     very short     → Beta(2, 10) → mean=0.17, mode≈0.11
        alpha_tv   = pm.Beta("alpha_tv",   alpha=8,  beta=3)
        alpha_ps   = pm.Beta("alpha_ps",   alpha=2,  beta=8)
        alpha_so   = pm.Beta("alpha_so",   alpha=5,  beta=6)
        alpha_disp = pm.Beta("alpha_disp", alpha=2,  beta=10)

        alphas = {"tv": alpha_tv, "paid_search": alpha_ps,
                  "social": alpha_so, "display": alpha_disp}

        # ── PRIORS: Hill saturation (k and ec) ───────────────────────────────

        # k (Hill slope): must be > 0. HalfNormal(2) puts most mass in (0, 4),
        # covering the full range of plausible curvatures (1=hyperbolic, 3=sharp S).
        # We use slightly different scales per channel based on our DGP knowledge,
        # but keep them broad enough to not over-constrain the model.
        k_tv   = pm.HalfNormal("k_tv",   sigma=3.0)
        k_ps   = pm.HalfNormal("k_ps",   sigma=2.5)
        k_so   = pm.HalfNormal("k_so",   sigma=2.0)
        k_disp = pm.HalfNormal("k_disp", sigma=3.5)

        ks = {"tv": k_tv, "paid_search": k_ps,
              "social": k_so, "display": k_disp}

        # ec (half-saturation): must be > 0. Since adstock is normalised to [0,~1]
        # by p95, ec is interpretable on a [0,1] scale.
        # Beta(4, 6) → mean≈0.4, Beta(6, 4) → mean≈0.6 — channel-informed priors
        # that keep ec in a sensible [0,1] range.
        ec_tv   = pm.Beta("ec_tv",   alpha=4, beta=6)   # mean=0.40 → saturates fast
        ec_ps   = pm.Beta("ec_ps",   alpha=6, beta=4)   # mean=0.60 → moderate
        ec_so   = pm.Beta("ec_so",   alpha=7, beta=3)   # mean=0.70 → room to grow
        ec_disp = pm.Beta("ec_disp", alpha=3, beta=7)   # mean=0.30 → very fast sat

        ecs = {"tv": ec_tv, "paid_search": ec_ps,
               "social": ec_so, "display": ec_disp}

        # ── PRIORS: Channel coefficients (β) ─────────────────────────────────

        # β_c is the maximum revenue contribution of channel c (when saturated = 1).
        # Canada's true values: TV=$320K, Search=$260K, Social=$200K, Display=$80K.
        # HalfNormal(400_000) puts 99% of mass below ~$925K — diffuse but positive.
        # Positive constraint is correct: more spend cannot reduce expected revenue.
        beta_tv   = pm.HalfNormal("beta_tv",   sigma=400_000)
        beta_ps   = pm.HalfNormal("beta_ps",   sigma=400_000)
        beta_so   = pm.HalfNormal("beta_so",   sigma=400_000)
        beta_disp = pm.HalfNormal("beta_disp", sigma=150_000)

        betas = {"tv": beta_tv, "paid_search": beta_ps,
                 "social": beta_so, "display": beta_disp}

        # ── DETERMINISTIC: Baseline ───────────────────────────────────────────

        trend      = intercept + trend_slope * t_std
        seasonality = pm.math.dot(fourier, fourier_coefs)

        # Holiday effect: additive lift/drag expressed as revenue amount.
        # holiday_matrix is (T, 12); holiday_deltas is (12,).
        # dot product gives (T,) — the total holiday revenue delta each week.
        holiday_effect = pm.math.dot(holiday_matrix, holiday_deltas) * intercept

        baseline = pm.Deterministic("baseline", trend + seasonality + holiday_effect)

        # ── DETERMINISTIC: Media contributions ───────────────────────────────

        channel_contributions = []
        for ch in CHANNELS:
            # Fixed lag matrix and lags passed in as data constants
            lag_mat = pt.as_tensor_variable(
                inputs["lag_matrices"][ch].astype("float64")
            )
            p95_val = inputs["p95"][ch]   # fixed scalar from preprocessing

            # Vectorised adstock: single dot product, no scan loop
            adstock_ch = pytensor_geometric_adstock_vec(
                lag_mat, inputs["lags"], alphas[ch]
            )

            # Normalise by fixed p95 constant (same as DGP)
            adstock_norm_ch = adstock_ch / p95_val

            # Hill saturation
            saturated_ch = pytensor_hill(adstock_norm_ch, ks[ch], ecs[ch])

            # Channel revenue contribution
            contrib_ch = pm.Deterministic(
                f"contrib_{ch}", betas[ch] * saturated_ch
            )
            channel_contributions.append(contrib_ch)

        total_media = sum(channel_contributions)

        # ── DETERMINISTIC: Predicted revenue ────────────────────────────────
        mu = pm.Deterministic("mu", baseline + total_media)

        # ── LIKELIHOOD ───────────────────────────────────────────────────────
        revenue = pm.Normal("revenue", mu=mu, sigma=sigma, observed=revenue_obs)

    return model


