def run_phase3(
    sampling_draws:   int   = 1000,
    sampling_tune:    int   = 1000,
    sampling_chains:  int   = 4,
    target_accept:    float = 0.90,
    prior_samples:    int   = 500,
    save_idata:       bool  = True,
):
    """
    Full Phase 3 pipeline:
        1. Load data
        2. Build model inputs
        3. Build PyMC model
        4. Prior predictive check
        5. MCMC sampling
        6. Diagnostics
        7. Parameter recovery
        8. Posterior contribution decomposition

    Parameters
    ----------
    sampling_draws  : Posterior draws per chain.
    sampling_tune   : Warmup (tuning) steps per chain.
    sampling_chains : Number of independent MCMC chains.
    target_accept   : NUTS target acceptance rate.
    prior_samples   : Prior predictive samples.
    save_idata      : If True, save InferenceData to outputs/idata_canada.nc.
    """
    print("=" * 65)
    print("MapleThread Outdoor Co. — Phase 3: Single-Region Bayesian MMM")
    print(f"Region: Canada  |  {N_WEEKS} weeks")
    print("=" * 65)

    # ── Step 1: Load data ─────────────────────────────────────────────────────
    print("\n[1/7] Loading data...")
    raw_df, gt_df = load_canada_data()

    # ── Step 2: Build model inputs ────────────────────────────────────────────
    print("\n[2/7] Building model inputs...")
    inputs = build_model_inputs(raw_df)
    print(f"  t_std range:         [{inputs['t_std'].min():.2f}, {inputs['t_std'].max():.2f}]")
    for ch in CHANNELS:
        print(f"  p95 ({ch:>12s}): {inputs['p95'][ch]:>12,.0f}")

    # ── Step 3: Build model ───────────────────────────────────────────────────
    print("\n[3/7] Building PyMC model...")
    model = build_model(inputs)
    print(f"  Free parameters: {len(model.free_RVs)}")
    print(f"  {model}")

    # ── Step 4: Prior predictive check ────────────────────────────────────────
    print("\n[4/7] Prior predictive check...")
    prior_pred = run_prior_predictive(model, inputs, n_samples=prior_samples)

    # ── Step 5: MCMC sampling ─────────────────────────────────────────────────
    print("\n[5/7] MCMC sampling...")
    idata = run_sampling(
        model,
        draws=sampling_draws,
        tune=sampling_tune,
        chains=sampling_chains,
        target_accept=target_accept,
    )

    # ── Step 6: Diagnostics ───────────────────────────────────────────────────
    print("\n[6/7] Diagnostics...")
    summary = run_diagnostics(idata)

    # ── Step 7: Parameter recovery ────────────────────────────────────────────
    print("\n[7/7] Parameter recovery & contribution plots...")
    plot_parameter_recovery(idata)
    plot_posterior_contributions(idata, inputs)

    # ── Save InferenceData ────────────────────────────────────────────────────
    if save_idata:
        idata_path = "outputs/idata_canada.nc"
        idata.to_netcdf(idata_path)
        print(f"\n  ✓ InferenceData saved: {idata_path}")

    print("\n" + "=" * 65)
    print("Phase 3 complete. ✓")
    print("=" * 65)

    return model, idata, inputs


