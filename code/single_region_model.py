# 6. MCMC SAMPLING & DIAGNOSTICS
# ══════════════════════════════════════════════════════════════════════════════

def run_sampling(model: pm.Model,
                 draws: int = 1000,
                 tune: int = 1000,
                 chains: int = 4,
                 target_accept: float = 0.90) -> az.InferenceData:
    """
    Sample the posterior with NUTS.

    Sampler settings
    ----------------
    tune=1000   : Warmup steps for step-size and mass-matrix adaptation.
                  More than default (500) because MMM models have correlated
                  geometry (beta-alpha-k-ec are partially identifiable).
    draws=1000  : Posterior samples per chain. 4 chains × 1000 = 4000 total.
    target_accept=0.90 : Higher than default (0.8) to reduce divergences in
                  regions of high curvature (Hill function near saturation).

    Returns
    -------
    az.InferenceData with posterior, log_likelihood, and observed_data groups.
    """
    print(f"\n  Sampling posterior (chains={chains}, draws={draws}, tune={tune})...")
    print(f"  This may take several minutes for a 156-week model.\n")

    with model:
        idata = pm.sample(
            draws=draws,
            tune=tune,
            chains=chains,
            target_accept=target_accept,
            random_seed=RANDOM_SEED,
            progressbar=True,
            idata_kwargs={"log_likelihood": True},
        )

    return idata


def run_diagnostics(idata: az.InferenceData,
                    save_path: str = "outputs/fig_trace.png"):
    """
    Run ArviZ diagnostics and save trace plots for key parameters.

    Checks
    ------
    - R-hat: should be < 1.01 for all parameters (< 1.05 is acceptable).
    - Effective Sample Size (ESS): bulk and tail ESS should be > 400.
    - Divergences: any divergences warrant investigation.
    - MCSE: Monte Carlo standard error should be small relative to posterior sd.

    Parameters plotted
    ------------------
    We plot a curated subset: one representative parameter per type.
    Full trace plots for all 20+ parameters would be unreadable.
    """
    print("\n  Running MCMC diagnostics...")

    # ── R-hat and ESS summary ────────────────────────────────────────────────
    scalar_vars = [
        "intercept", "trend_slope", "sigma",
        "alpha_tv", "alpha_ps", "alpha_so", "alpha_disp",
        "k_tv", "k_ps", "k_so", "k_disp",
        "ec_tv", "ec_ps", "ec_so", "ec_disp",
        "beta_tv", "beta_ps", "beta_so", "beta_disp",
    ]

    summary = az.summary(idata, var_names=scalar_vars, round_to=4)
    print("\n  ── Posterior Summary ──")
    print(summary[["mean", "sd", "hdi_3%", "hdi_97%", "r_hat", "ess_bulk"]].to_string())

    n_divergences = int(idata.sample_stats["diverging"].values.sum())
    print(f"\n  Divergences: {n_divergences}")
    if n_divergences > 0:
        print("  ⚠ Divergences detected — consider reparameterisation or higher target_accept.")
    else:
        print("  ✓ No divergences.")

    rhat_vals = summary["r_hat"].dropna()
    max_rhat  = rhat_vals.max()
    n_bad     = (rhat_vals > 1.01).sum()
    print(f"\n  Max R-hat:        {max_rhat:.4f}  (target: < 1.01)")
    print(f"  Parameters > 1.01: {n_bad}")

    min_ess = summary["ess_bulk"].min()
    print(f"  Min bulk ESS:     {min_ess:.0f}  (target: > 400)")

    # ── Trace plots ──────────────────────────────────────────────────────────
    # Plot 8 representative parameters — one from each prior family
    trace_vars = [
        "intercept", "trend_slope", "sigma",
        "alpha_tv", "alpha_ps",
        "k_tv", "ec_tv", "beta_tv",
    ]

    axes = az.plot_trace(
        idata,
        var_names=trace_vars,
        figsize=(14, 18),
        compact=True,
    )
    fig = axes.ravel()[0].get_figure()
    fig.suptitle(
        "MCMC Trace Plots — Canada (Representative Parameters)\n"
        "Left: posterior density  |  Right: sample trace (should look like 'fuzzy caterpillar')",
        fontsize=11, fontweight="bold", y=1.005,
    )
    plt.tight_layout()
    plt.savefig(save_path, dpi=120, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"\n  ✓ Trace plot saved: {save_path}")

    return summary


