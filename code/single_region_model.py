# 5. PRIOR PREDICTIVE CHECK
# ══════════════════════════════════════════════════════════════════════════════

def run_prior_predictive(model: pm.Model,
                          inputs: dict,
                          n_samples: int = 500,
                          save_path: str = "outputs/fig_prior_predictive.png"):
    """
    Sample from the prior only and plot implied revenue distribution.

    The goal: verify the prior allows a plausible range of revenues without
    permitting absurdities (e.g. negative billions or positive trillions).
    Canada's observed revenue range: ~$540K–$1.15M.

    A good prior predictive should:
      - Cover the observed range comfortably
      - Not put appreciable mass below $0 or above $5M
    """
    print("\n  Running prior predictive check...")
    with model:
        prior_pred = pm.sample_prior_predictive(
            samples=n_samples,
            random_seed=RANDOM_SEED,
        )

    observed    = inputs["revenue"]
    dates       = pd.to_datetime(inputs["dates"])
    prior_draws = prior_pred.prior_predictive["revenue"].values  # (1, n_samples, T)
    prior_draws = prior_draws[0]  # → (n_samples, T)

    p05  = np.percentile(prior_draws, 5,  axis=0)
    p25  = np.percentile(prior_draws, 25, axis=0)
    p50  = np.percentile(prior_draws, 50, axis=0)
    p75  = np.percentile(prior_draws, 75, axis=0)
    p95  = np.percentile(prior_draws, 95, axis=0)

    fig, axes = plt.subplots(1, 2, figsize=(16, 5))
    fig.suptitle(
        "Prior Predictive Check — Canada\n"
        "Do the priors allow plausible revenue trajectories?",
        fontsize=13, fontweight="bold",
    )

    # ── Left: time-series fan chart ───────────────────────────────────────────
    ax = axes[0]
    ax.fill_between(dates, p05, p95, alpha=0.20, color="#4361EE", label="5–95th pct")
    ax.fill_between(dates, p25, p75, alpha=0.35, color="#4361EE", label="25–75th pct")
    ax.plot(dates, p50,      color="#4361EE", lw=1.5, label="Median prior")
    ax.plot(dates, observed, color="#E63946", lw=1.5, alpha=0.9, label="Observed revenue")
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x/1e6:.1f}M"))
    ax.set_title("Prior predictive fan vs. observed", fontsize=11)
    ax.set_xlabel("Date")
    ax.set_ylabel("Revenue")
    ax.legend(fontsize=8, loc="upper left")

    # ── Right: marginal distribution of prior revenue ─────────────────────────
    ax = axes[1]
    flat = prior_draws.flatten()
    # Clip to ±$5M for display — extreme tails are less informative
    clipped = flat[(flat > -5e6) & (flat < 5e6)]
    ax.hist(clipped / 1e6, bins=80, color="#4361EE", alpha=0.65,
            edgecolor="white", linewidth=0.3)
    obs_min, obs_max = observed.min() / 1e6, observed.max() / 1e6
    ax.axvspan(obs_min, obs_max, alpha=0.25, color="#E63946",
               label=f"Observed range\n(${obs_min:.2f}M – ${obs_max:.2f}M)")
    ax.axvline(0, color="black", lw=1.2, linestyle="--", alpha=0.6, label="Zero revenue")
    ax.set_xlabel("Revenue ($M)")
    ax.set_ylabel("Count (prior draws)")
    ax.set_title("Marginal distribution of prior draws", fontsize=11)
    ax.legend(fontsize=8)

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()

    # ── Summary statistics ────────────────────────────────────────────────────
    pct_negative = (prior_draws < 0).mean() * 100
    pct_above_5m = (prior_draws > 5e6).mean() * 100
    print(f"  Prior predictive summary:")
    print(f"    Median prior revenue: ${np.median(prior_draws):,.0f}")
    print(f"    Prior 5–95th range:   ${p05.mean():,.0f} – ${p95.mean():,.0f} (avg per week)")
    print(f"    % draws < $0:         {pct_negative:.2f}%  (target: < 5%)")
    print(f"    % draws > $5M:        {pct_above_5m:.2f}%  (target: < 1%)")
    print(f"  ✓ Prior predictive saved: {save_path}")

    return prior_pred


