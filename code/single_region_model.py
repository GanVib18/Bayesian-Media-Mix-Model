# 8. POSTERIOR CONTRIBUTION DECOMPOSITION
# ══════════════════════════════════════════════════════════════════════════════

def plot_posterior_contributions(idata: az.InferenceData,
                                  inputs: dict,
                                  save_path: str = "outputs/fig_posterior_contributions.png"):
    """
    Plot posterior mean channel contributions vs. ground-truth contributions.

    This produces a stacked area chart using the posterior mean of each
    channel's deterministic contribution. Shaded bands show the 94% credible
    interval, giving an honest uncertainty representation.
    """
    print("\n  Plotting posterior contributions...")

    posterior = idata.posterior
    dates     = pd.to_datetime(inputs["dates"])
    revenue   = inputs["revenue"]

    fig, axes = plt.subplots(2, 1, figsize=(15, 11), sharex=True)
    fig.suptitle(
        "Canada — Posterior Revenue Decomposition\n"
        "Top: posterior mean contributions  |  Bottom: observed vs. predicted",
        fontsize=13, fontweight="bold",
    )

    # ── Top panel: stacked contribution areas ─────────────────────────────────
    ax = axes[0]
    baseline_post = posterior["baseline"].values  # (chains, draws, T)
    baseline_mean = baseline_post.reshape(-1, inputs["T"]).mean(axis=0)

    ax.fill_between(dates, 0, baseline_mean, alpha=0.5,
                    color=PALETTE["baseline"], label="Baseline")
    bottom = baseline_mean.copy()

    for ch in CHANNELS:
        contrib = posterior[f"contrib_{ch}"].values.reshape(-1, inputs["T"])
        c_mean  = contrib.mean(axis=0)
        c_lo    = np.percentile(contrib, 3, axis=0)
        c_hi    = np.percentile(contrib, 97, axis=0)

        ax.fill_between(dates, bottom, bottom + c_mean, alpha=0.75,
                        color=PALETTE[ch], label=CHANNEL_LABELS[ch])
        bottom += c_mean

    ax.plot(dates, revenue, color="white", lw=0.8, alpha=0.6, label="Observed revenue")
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
    ax.set_ylabel("Revenue ($)")
    ax.legend(loc="upper left", fontsize=9, ncol=3)

    # ── Bottom panel: posterior predicted vs. observed ────────────────────────
    ax = axes[1]
    mu_post = posterior["mu"].values.reshape(-1, inputs["T"])  # (total_draws, T)
    mu_mean = mu_post.mean(axis=0)
    mu_lo   = np.percentile(mu_post, 3,  axis=0)
    mu_hi   = np.percentile(mu_post, 97, axis=0)

    ax.fill_between(dates, mu_lo, mu_hi, alpha=0.25, color="#4361EE",
                    label="94% posterior predictive band")
    ax.plot(dates, mu_mean, color="#4361EE", lw=1.5, label="Posterior mean")
    ax.plot(dates, revenue, color="#E63946", lw=1.2, alpha=0.85, label="Observed revenue")
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(lambda x, _: f"${x/1e3:.0f}K"))
    ax.set_xlabel("Date")
    ax.set_ylabel("Revenue ($)")
    ax.legend(loc="upper left", fontsize=9)

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    plt.close()
    print(f"  ✓ Contribution decomposition saved: {save_path}")


